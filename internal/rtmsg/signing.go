package rtmsg

// SigningKeyGenFailed - "сгенерировать_приватный_ключ" не смог
// сгенерировать ключ (внутренняя ошибка OpenSSL EVP/Go crypto/rand) -
// практически недостижимо на настоящей ОС, защитная проверка того же
// рода, что и AESRandomFailed (crypto.go).
const SigningKeyGenFailed = "сгенерировать_приватный_ключ: не удалось сгенерировать ключ"

// UnknownSignatureAlgorithm - "сгенерировать_приватный_ключ(алгоритм)" со
// значением "алгоритм" вне диапазона членов "АлгоритмПодписи" - возможно,
// только передав голое Целое напрямую, не через сам enum (тот же случай,
// что и UnknownHashAlgorithm у "хеш").
const UnknownSignatureAlgorithm = "сгенерировать_приватный_ключ: неизвестный алгоритм"

// SigningInvalidPrivateKey - "получить_публичный_ключ"/"подписать" со
// строкой, которая не разбирается как PEM-приватный ключ (не PEM вовсе,
// повреждён, или PEM другого типа объекта, не ключа) - аварийное
// завершение, тот же принцип, что и у остального среза crypto.go/aes.go
// (структурно некорректный вход - не то же самое, что "не сошлось" у
// проверки подписи, см. SigningInvalid Signature ниже).
const SigningInvalidPrivateKey = "не удалось разобрать приватный ключ (ожидался PEM)"

// SigningInvalidPublicKey - тот же случай для "проверить_подпись" и
// строки "публичный_ключ".
const SigningInvalidPublicKey = "не удалось разобрать публичный ключ (ожидался PEM)"

// SigningInvalidSignatureHex - "проверить_подпись" со строкой "подпись",
// не являющейся HEX (тем форматом, что возвращает "подписать") -
// аварийное завершение, СТРУКТУРНАЯ ошибка входа (как и PrivateKey/
// PublicKey выше) - в отличие от НЕСОШЕДШЕЙСЯ (но синтаксически валидной)
// подписи, которая возвращает "ложь", не паникует (см. package doc
// signing.go про это разделение).
const SigningInvalidSignatureHex = "проверить_подпись: подпись не в формате HEX"
