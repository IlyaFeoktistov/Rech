package rtmsg

// Бинарно-безопасный файловый ввод-вывод ("прочитать_байты"/"записать_
// байты"/"прочитать_файл_байты"/"записать_в_файл_байты", Список<Байт>
// вместо Строка) и разбор multipart/form-data - раздача/загрузка файлов
// по HTTP (docs/ROADMAP.md).

// ReadBytesInvalidMax - сообщение при "прочитать_байты", если максимум
// байт <= 0 - тот же смысл, что ReadInvalidMax (rtmsg.go), но с верным
// именем функции в тексте (докстрока ReadInvalidMax объясняет, почему имя
// функции внутри сообщения важно - позволяет отличить панику одной
// функции от другой внутри `поймать (x: Паника)`).
const ReadBytesInvalidMax = "прочитать_байты: максимум байт должен быть положительным числом"

// ReadBytesIOFailed - сообщение при "прочитать_байты", если сам системный
// вызов чтения (fread) вернул ошибку - тот же смысл, что ReadIOFailed.
const ReadBytesIOFailed = "прочитать_байты: ошибка чтения файла"

// WriteBytesIOFailed - сообщение при "записать_байты", если запись не
// удалась целиком - тот же смысл, что WriteIOFailed.
const WriteBytesIOFailed = "записать_байты: ошибка записи в файл"

// MultipartMissingBoundary - сообщение при "разобрать_multipart", если
// заголовок Content-Type запроса/ответа не несёт "boundary=" вовсе (не
// multipart/form-data, или значение испорчено) - без границы разбор
// невозможен в принципе, не частичный успех.
const MultipartMissingBoundary = "разобрать_multipart: заголовок Content-Type не содержит boundary"
