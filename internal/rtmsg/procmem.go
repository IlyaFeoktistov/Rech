package rtmsg

// ProcAttachFailed - "подключиться_к_процессу" не смог подключиться к
// чужому процессу: нет процесса с таким pid, недостаточно прав (POSIX -
// ptrace_scope/CAP_SYS_PTRACE; Windows - привилегии отладки) или ОС не
// поддерживает эту операцию вовсе (см. package doc internal/backend/
// cbackend/procmem.go - платформы, кроме Linux/Windows).
const ProcAttachFailed = "подключиться_к_процессу: не удалось подключиться к процессу"

// ProcDetachFailed - "отключиться" (ЧужойПроцесс) не смог отключиться -
// процесс, к которому подключились, уже не существует.
const ProcDetachFailed = "отключиться: не удалось отключиться от процесса"

// ProcMemReadFailed - "прочитать" (ЧужойПроцесс) не смог прочитать байты
// по указанному адресу - адрес вне отображённых страниц процесса, размер
// не положителен, или процесс завершился между подключением и чтением.
const ProcMemReadFailed = "прочитать: не удалось прочитать память процесса"

// ProcMemWriteFailed - "записать" (ЧужойПроцесс) не смог записать байты по
// указанному адресу - тот же набор причин, что и ProcMemReadFailed, либо
// страница доступна только для чтения.
const ProcMemWriteFailed = "записать: не удалось записать в память процесса"

// ProcMemPatternEmpty - "найти" (Процесс) вызван с пустым шаблоном поиска
// (Список<Байт> нулевой длины) - совпадение с пустой последовательностью
// байт бессмысленно (совпало бы с любым смещением сразу).
const ProcMemPatternEmpty = "найти: шаблон поиска не может быть пустым"
