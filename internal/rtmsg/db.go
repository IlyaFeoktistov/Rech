package rtmsg

import "fmt"

// DBConnectFailed - сообщение при "подключиться_к_бд", если подключение не
// удалось (неверные учётные данные, недоступный сервер и т. п. - не
// различается дальше, как и у SocketConnectFailed). Строка подключения не
// включена в сообщение - она может нести пароль.
const DBConnectFailed = "подключиться_к_бд: не удалось подключиться"

// DBUnsupportedScheme - сообщение при "подключиться_к_бд", если схема
// строки подключения не входит в число известных ("sqlite:", "postgres://",
// "mysql://").
const DBUnsupportedScheme = "подключиться_к_бд: неизвестная схема строки подключения (ожидается \"sqlite:\", \"postgres://\" или \"mysql://\")"

// DBQueryFailedTemplate/DBQueryFailedFormat - сообщение при "запросить",
// если СУБД вернула ошибку выполнения запроса (некорректный SQL,
// отсутствующая таблица и т. п.) - %s - текст запроса, как передан
// вызывающей стороной. Template встраивается в C дословно (cbackend -
// snprintf на настоящий текст запроса, известный только в рантайме),
// Format вызывает его же через fmt.Sprintf - оба обязаны давать
// побайтово одинаковый результат.
const DBQueryFailedTemplate = "запросить: ошибка выполнения запроса \"%s\""

func DBQueryFailedFormat(sql string) string {
	return fmt.Sprintf(DBQueryFailedTemplate, sql)
}

// DBExecFailedTemplate/DBExecFailedFormat - то же самое для "выполнить".
const DBExecFailedTemplate = "выполнить: ошибка выполнения запроса \"%s\""

func DBExecFailedFormat(sql string) string {
	return fmt.Sprintf(DBExecFailedTemplate, sql)
}

// DBCheckoutTimeout - сообщение при "запросить"/"выполнить", если "бд.
// таймаут_пула_мс" файла проекта задан и свободное соединение из пула не
// освободилось за это время (rech_db_checkout/dbQuery/dbExec) - отличается
// от DBQueryFailedTemplate/DBExecFailedTemplate текстом специально:
// вызывающий код (например, HTTP-обработчик) может сравнить сообщение
// внутри "поймать (x: Паника)" и отличить "пул перегружен" от настоящей
// ошибки самого запроса, тем же приёмом, что уже используется для
// "принять_http: ошибка получения запроса" в http_сервере.
const DBCheckoutTimeout = "БД: не удалось получить свободное соединение из пула вовремя"

// DBInvalidParamType - сообщение при "запросить"/"выполнить", если элемент
// списка параметров боксирует значение типа, для которого нет
// представления в SQL (только Целое/Действительное/Строка/Логическое/
// Ничто допустимы).
const DBInvalidParamType = "недопустимый тип параметра БД (допустимы только Целое/Действительное/Строка/Логическое/Ничто)"

// DBTooFewParams - сообщение при "запросить"/"выполнить", если в SQL
// больше "?" (плейсхолдеров), чем элементов в списке параметров.
const DBTooFewParams = "недостаточно параметров БД для количества \"?\" в запросе"

// DBUnreachableKind - защитное сообщение в "rech_db_query"/"rech_db_exec"/
// "rech_db_close" (cbackend, ветка switch(db->kind) "default") - в
// программе, где статически известно, что литерал строки подключения несёт
// только часть из трёх схем (internal/dbscheme.Set - "не
// линковать безусловно все три"), сгенерированный C эмитит код только для
// НУЖНЫХ СУБД. Эта ветка недостижима при корректной работе "подключиться_к_
// бд" (db->kind мог быть установлен только на одну из СКОМПИЛИРОВАННЫХ
// веток), сообщение - только страховка на случай порчи памяти/бага
// генератора, не ожидаемый пользовательский сценарий.
const DBUnreachableKind = "внутренняя ошибка: недопустимый дескриптор БД"

// DBTxResolved - "тр.вложенная(...)" на транзакции, которая уже
// зафиксирована или откачена (явным "откатить()" или завершением колбэка).
const DBTxResolved = "вложенная: транзакция уже завершена"
