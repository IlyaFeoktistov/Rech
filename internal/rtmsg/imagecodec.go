const PNGEncodeFailed = "png_кодировать_файл: не удалось записать PNG"

// JPEGOpenFailed - "jpeg_декодировать_файл" не смог открыть файл.
const JPEGOpenFailed = "jpeg_декодировать_файл: не удалось открыть файл"

// JPEGDecodeFailed - "jpeg_декодировать_файл" - файл открыт, но libjpeg не
