package rtmsg

// Base64URLInvalidInput - "декодировать_base64url(текст)" на строке,
// содержащей символ вне алфавита RFC 4648 §5 (A-Z, a-z, 0-9, "-", "_") или
// с длиной, не кратной корректному хвосту base64 (ровно один "лишний"
// символ в последней группе) - аварийное завершение, тем же принципом, что
// и "подстрока"/"случайное_целое" (в языке ещё нет исключений, которыми
// это можно было бы поймать).
const Base64URLInvalidInput = "декодировать_base64url: некорректный base64url"

// UnknownHashAlgorithm - "хеш(алгоритм, данные)" со значением "алгоритм" вне
// диапазона членов "АлгоритмХеша" (semantic/types.go, StandardEnums) -
// возможно только передав голое Целое напрямую, не через сам enum (тип
// параметра - Kind int, компилятор не проверяет диапазон, см. package doc
// internal/builtins.builtins.go). Аварийное завершение, тем же принципом,
// что и остальные защитные проверки этого файла.
const UnknownHashAlgorithm = "хеш: неизвестный алгоритм"

// AESCiphertextInvalid - "расшифровать(шифротекст, ключ)" на строке,
// которая не является корректным выводом "зашифровать": не HEX вовсе, HEX
// нечётной длины, или короче минимума (12 байт nonce + 16 байт тега
// аутентификации GCM - см. package doc aes.go). Аварийное завершение, тем
// же принципом, что и Base64URLInvalidInput выше.
const AESCiphertextInvalid = "расшифровать: некорректный шифротекст"

// AESAuthenticationFailed - "расшифровать" с неверным ключом ИЛИ с
// шифротекстом, изменённым после шифрования (GCM - аутентифицированное
// шифрование, "тег" защищает целостность так же, как и секретность) - обе
// причины неотличимы друг от друга специально (сообщать взломщику, ЧТО
// именно не сошлось, - утечка информации), аварийное завершение.
const AESAuthenticationFailed = "расшифровать: не удалось подтвердить подлинность (неверный ключ или повреждённые данные)"

// AESRandomFailed - "зашифровать" не смог получить случайный nonce от
// системного генератора (RAND_bytes в cbackend, crypto/rand.Read в
// interp) - практически недостижимо на настоящей ОС, защитная проверка
// того же рода, что и остальные panic-и этого файла, не ожидаемый в
// обычной работе исход.
const AESRandomFailed = "зашифровать: не удалось получить случайные байты"
