package ir

// TypeOfExpr - "тип <Имя>" - дескриптор типа Имя, известного уже во время
// компиляции (в отличие от "значение.тип()", который читает дескриптор
// динамического значения в рантайме) - Type несёт разрешённый Rech-тип
// Имя (примитив или сущность/структура), само выражение имеет тип
// KindTypeInfo ("Тип").
type TypeOfExpr struct {
	Type Type
}

func (*TypeOfExpr) expr() {}

// AsExpr - "<значение> как <Тип>" - разбоксирование "Значение" обратно к
// конкретному Type, с рантайм-проверкой фактического типа (см.
// ast.AsExpr). Value несёт выражение типа KindAny.
type AsExpr struct {
	Value Expr
	To    Type
}

func (*AsExpr) expr() {}
