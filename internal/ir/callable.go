package ir

// FuncRefExpr - "&имя": ссылка на уже объявленную функцию как на
// значение типа "Вызываемый" - без вызова. FuncName уже проверено
// семантическим анализом как обычная (не generic, не внешняя, не
// встроенная) функция программы.
type FuncRefExpr struct {
	FuncName string
	Type     Type
}

func (*FuncRefExpr) expr() {}

// CaptureVar - одна захваченная переменная лямбды. ByRef false (умолчание,
// единственный вариант до явного списка захвата, см. package doc
// LambdaExpr.Captures) - копия значения из окружающей области видимости на
// момент создания лямбды, а не живая связь: для Структура (значение по
// умолчанию) это обычная копия содержимого, для Сущность (ссылка по
// умолчанию) - копия указателя (значения по-прежнему разделяются, но сама
// переменная замыкания и переменная снаружи - независимые связывания),
// тем же правилом, что и у обычного присваивания/передачи аргумента -
// никакого отдельного механизма замыкания вводить не потребовалось. Type -
// тип ЗНАЧЕНИЯ (T), а не указателя.
//
// ByRef true ("&имя" в явном списке захвата) - Type, наоборот, уже сам
// "Указатель<T>" (см. semantic.analyzeLambdaExpr/pointerTypeFor): поле
// окружения хранит адрес внешней переменной, не копию значения - запись
// внутри тела лямбды видна снаружи. Внутри самого тела эта переменная,
// тем не менее, ведёт себя как обычная T, не как Указатель<T> - каждое из
// НЕСКОЛЬКИХ мест семантического анализа, где имя превращается в
// IR-выражение (analyzeExpr на *ast.Identifier для чтения, *ast.Assign
// для записи - других мест нет: "++"/"--"/"&имя"/"?=" для такого имени
// отклоняются как явно неподдержанные), прозрачно оборачивает Identifier
// этого же имени (уже типа "Указатель<T>", ctx.byRefCaptures) в
// DerefExpr/DerefAssignStmt - тот же приём, что и у ручного "*указ"/
// "*указ = значение", без единого нового вида выражения.
type CaptureVar struct {
	Name  string
	Type  Type
	ByRef bool
}

// LambdaExpr - "функция(<парам>: <Тип>, ...): <ТипРезультата> { <тело> }"
// без имени, в позиции выражения - Captures перечисляет свободные
// переменные тела, найденные семантическим анализом (analyzeLambdaExpr) в
// порядке первого использования; Type - Вызываемый-тип с той же сигнатурой
// (Params/Result), под которым эта же лямбда зарегистрирована в
// Program.Callables.
type LambdaExpr struct {
	Name       string
	Params     []Param
	ReturnType Type
	HasReturn  bool
	Captures   []CaptureVar
	Body       []Stmt
	Type       Type
}

func (*LambdaExpr) expr() {}

// CallValueExpr - вызов ЗНАЧЕНИЯ типа "Вызываемый" ("ф(<арг>, ...)", где ф -
// переменная/поле, не имя объявленной функции) - в отличие от
// CallExpr (вызов по статически известному имени), здесь вызывается сама
// Value (указатель на функцию + указатель на окружение замыкания,
// см. package doc internal/backend/cbackend/callable.go). Естественный
// (падежный) вызов к этой форме не относится - только обычный "ф(...)".
type CallValueExpr struct {
	Value     Expr
	Args      []Expr
	Type      Type
	HasReturn bool
}

func (*CallValueExpr) expr() {}
