package ir

// LaunchExpr - "запустить <вызов>(...)"/"поручить <асинхронная
// функция>(...)": запускает Value (значение типа Вызываемый - &функция,
// лямбда, переменная, синтезированная обёртка метода) с аргументами Args
// и немедленно возвращает задачу типа TaskType(сигнатура Value), не
// дожидаясь завершения.
type LaunchExpr struct {
	Value Expr
	Args  []Expr
	// Coroutine - на лёгком планировщике корутин вместо потока ОС:
	// "поручить" и сахар "дождаться <асинхронная функция>(...)". Тип задачи
	// от этого не зависит - как её дождаться, задача знает сама.
	Coroutine bool
}

func (*LaunchExpr) expr() {}

// AwaitExpr - "дождаться <выражение>": блокирует до завершения задачи
// Task; необработанное внутри неё исключение выбрасывается заново здесь же.
// Type/HasReturn - результат сигнатуры задачи.
type AwaitExpr struct {
	Task      Expr
	Type      Type
	HasReturn bool
}

func (*AwaitExpr) expr() {}
