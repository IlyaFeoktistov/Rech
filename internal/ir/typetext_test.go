package ir

import "testing"

func TestDisplayTypesRewritesCallableCanon(t *testing.T) {
	for in, want := range map[string]string{
		`"г" имеет тип ?Вызываемый<Целое>Целое и может быть Ничто`: `"г" имеет тип ?Вызываемый(Целое): Целое и может быть Ничто`,
		"ожидался Вызываемый<Целое, Строка>, получен Строка":       "ожидался Вызываемый(Целое, Строка), получен Строка",
		"Вызываемый<>": "Вызываемый()",
		"Список<Вызываемый<Список<Целое>>?Строка>":             "Список<Вызываемый(Список<Целое>): ?Строка>",
		"Вызываемый<Вызываемый<Целое>Целое>Вызываемый<>Строка": "Вызываемый(Вызываемый(Целое): Целое): Вызываемый(): Строка",
		"без типов": "без типов",
	} {
		if got := DisplayTypes(in); got != want {
			t.Errorf("DisplayTypes(%q) = %q, ожидалось %q", in, got, want)
		}
	}
}
