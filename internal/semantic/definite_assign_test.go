package semantic

import (
	"strings"
	"testing"
)

// definiteAssignSrc - функция главная с телом body после "Целое х = 1".
func definiteAssignSrc(body string) string {
	return "функция главная\n{\n    Целое х = 1\n" + body + "\n}\n"
}

// TestReadBeforeAssignRejected - чтение переменной, объявленной без
// значения, там, где хотя бы на одном пути она ещё не присвоена, - ошибка
// компиляции.
func TestReadBeforeAssignRejected(t *testing.T) {
	cases := map[string]string{
		"сразу":          "    Целое ч\n    вывести ч",
		"только в если":  "    Целое ч\n    если х > 0 {\n        ч = 1\n    }\n    вывести ч",
		"только в цикле": "    Целое ч\n    пока х < 3 {\n        ч = 1\n        х++\n    }\n    вывести ч",
		"инкремент":      "    Целое ч\n    ч++",
		"составное":      "    Целое ч\n    ч += 1",
		"сама в себя":    "    Целое ч\n    ч = ч + 1",
		"метод":          "    Список<Целое> список\n    список.добавить(1)",
		"лямбда":         "    Целое ч\n    Вызываемый(): Целое ф = функция(): Целое {\n        вернуть ч\n    }",
		"?=":             "    ?Целое ч\n    ч ?= 3",
		"попытаться без поймать": "    Целое ч\n    попытаться {\n        ч = 1\n    } поймать (е: Исключение) {\n    }\n    вывести ч",
		"переменная: Тип":        "    переменная ч: Целое\n    вывести ч",
	}
	for name, body := range cases {
		_, err := AnalyzeSource(t, definiteAssignSrc(body))
		if err == nil || !strings.Contains(err.Error(), "читается до присваивания") {
			t.Errorf("%s: ожидалась ошибка чтения до присваивания, получено %v", name, err)
		}
	}
}

// TestReadAfterAssignOnEveryPathAccepted - присваивание на каждом пути до
// чтения: в обеих ветках, ветка с выходом не в счёт, все ветки "выбрать",
// "попытаться" и "поймать", лямбда после присваивания.
func TestReadAfterAssignOnEveryPathAccepted(t *testing.T) {
	cases := map[string]string{
		"обе ветки":          "    Целое ч\n    если х > 0 {\n        ч = 1\n    } иначе {\n        ч = 2\n    }\n    вывести ч",
		"иначе выходит":      "    Целое ч\n    если х > 0 {\n        ч = 1\n    } иначе {\n        вернуть\n    }\n    вывести ч",
		"выбрать":            "    Целое ч\n    выбрать х\n    {\n        когда 1:\n            ч = 1\n        иначе:\n            ч = 2\n    }\n    вывести ч",
		"попытаться/поймать": "    Целое ч\n    попытаться {\n        ч = 1\n    } поймать (е: Исключение) {\n        ч = 2\n    }\n    вывести ч",
		"лямбда после":       "    Целое ч\n    ч = 5\n    Вызываемый(): Целое ф = функция(): Целое {\n        вернуть ч\n    }\n    вывести ф()",
		"переменная: Тип":    "    переменная ч: Целое\n    ч = 3\n    вывести ч",
		"коллекция":          "    Список<Целое> список\n    список = [1]\n    список.добавить(2)",
	}
	for name, body := range cases {
		if _, err := AnalyzeSource(t, definiteAssignSrc(body)); err != nil {
			t.Errorf("%s: неожиданная ошибка %v", name, err)
		}
	}
}
