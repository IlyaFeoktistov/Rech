func TestSynonymIsSameTypeBothWays(t *testing.T) {
	prog := parseProgram(t, `
синоним Числа = Список<Целое>
синоним Проверка<T> = Вызываемый(T): Логическое
синоним ?Может<T> = ?T

функция первое(числа: Числа, условие: Проверка<Целое>): ?Может<Целое>
{
    для число в числах {
        если условие(число) {
            вернуть число
        }
    }

    вернуть Ничто
}

функция главная
{
    переменная список: Список<Целое> = [1, 2]
    переменная числа: Числа = список
    переменная обратно: Список<Целое> = числа
    вывести первое(обратно, функция(ч: Целое): Логическое { вернуть ч > 1 }) ?? 0
}
`)
	var fn *ir.Function
	for _, f := range prog.Functions {
		if f.Name == "первое" {
			fn = f
		}
	}
	if fn == nil {
		t.Fatalf("функция \"первое\" не найдена")
	}
	if got := fn.Params[0].Type.String(); got != "Список<Целое>" {
		t.Fatalf("синоним Числа должен раскрыться в Список<Целое>, получено %s", got)
	}
	if fn.ReturnType.Kind != ir.KindNullable {
		t.Fatalf("?Может<Целое> должен раскрыться в nullable-тип, получено %s", fn.ReturnType)
	}
}

func TestSynonymErrors(t *testing.T) {
	cases := map[string]struct{ src, want string }{
		"повтор":              {"синоним А = Целое\nсиноним А = Строка\n", "объявлен более одного раза"},
		"имя занято":          {"сущность Точка\n{\n    имеет:\n        Целое x\n}\nсиноним Точка = Целое\n", "имя уже занято"},
		"цикл":                {"синоним А = Список<Б>\nсиноним Б = А\n", "по кругу"},
		"лишние аргументы":    {"синоним А = Целое\nфункция ф(х: А<Целое>)\n{\n}\n", "не принимает аргументов"},
		"нет аргументов":      {"синоним П<T> = Список<T>\nфункция ф(х: П)\n{\n}\n", "ожидает 1"},
		"nullable без ?":      {"синоним А = ?Целое\n", "тоже пишется с \"?\""},
		"? без nullable":      {"синоним ?А = Целое\n", "не nullable-тип"},
		"голое использование": {"синоним ?А = ?Целое\nфункция ф(х: А)\n{\n}\n", "пишите \"?А\""},
	}
	for name, c := range cases {
		t.Run(name, func(t *testing.T) {
			_, err := AnalyzeSource(t, c.src+"функция главная\n{\n}\n")
			if err == nil || !strings.Contains(err.Error(), c.want) {
				t.Fatalf("ожидалась ошибка с %q, получено %v", c.want, err)
			}
		})
	}
}

