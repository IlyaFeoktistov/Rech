package semantic

import "testing"

// TestAnalyzeEnumAndSynonymAsGenericArg - перечисление и встроенный синоним
// внутри "<...>" - тот же тип, что "Целое": литерал из элементов
// перечисления присваивается "Список<Цвет>", "новый" с таким именем находит
// инстанциацию.
func TestAnalyzeEnumAndSynonymAsGenericArg(t *testing.T) {
	_, err := AnalyzeSource(t, `
перечисление Цвет
{
    КРАСНЫЙ,
    ЗЕЛЁНЫЙ
}

функция главная
{
    Список<Цвет> сп = [Цвет.КРАСНЫЙ, Цвет.ЗЕЛЁНЫЙ]
    Цвет[] ещё = [Цвет.ЗЕЛЁНЫЙ]
    Словарь<Цвет, Строка> имена = новый Словарь<Цвет, Строка>()
    Список<Целое64> числа = новый Список<Целое64>()
    Список<Целое> те_же = числа
    вывести сп.длина() + ещё.длина() + имена.длина() + те_же.длина()
}
`)
	if err != nil {
		t.Fatalf("неожиданная ошибка: %v", err)
	}
}
