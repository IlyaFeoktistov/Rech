package semantic

import (
	"strings"
	"testing"

	"github.com/IlyaFeoktistov/Rech/internal/ir"
)

const inferSrc = `
сущность Коробка<T>
{
    имеет:
        T содержимое

    конструктор(содержимое: T)
    {
        этот.содержимое = содержимое
    }
}

функция первый<T>(список: Список<T>): T
{
    вернуть список.получить(0)
}

функция обернуть<T>(значение: T): Коробка<T>
{
    вернуть новая Коробка(значение)
}

функция применить<T, Р>(значение: T, ф: Вызываемый(T): Р): Р
{
    вернуть ф(значение)
}

функция главная
{
    переменная числа = [3, 1, 2]
    переменная перв = первый(числа)
    переменная коробка = новая Коробка("x")
    переменная ящик = обернуть(1.5)
    переменная текст = применить(4, функция (х: Целое): Строка { вернуть "" })
    переменная вложенный = первый(первый([[7, 8]]))
}
`

func TestInferGenericTypeArgs(t *testing.T) {
	prog := parseProgram(t, inferSrc)
	main := findFunc(prog, "главная")
	want := map[string]string{
		"перв": "Целое", "коробка": "Коробка<Строка>", "ящик": "Коробка<Действительное>", "текст": "Строка", "вложенный": "Целое",
	}
	for _, st := range main.Body {
		decl, ok := st.(*ir.VarDecl)
		if !ok {
			continue
		}
		if w, ok := want[decl.Name]; ok {
			if got := ir.TypeOf(decl.Value).String(); got != w {
				t.Errorf("%s: ожидался тип %s, получен %s", decl.Name, w, got)
			}
		}
	}
	if findFunc(prog, "обернуть<Действительное>") == nil {
		t.Fatalf("ожидалась инстанциация обернуть<Действительное>")
	}
}

func TestInferGenericErrors(t *testing.T) {
	cases := map[string]struct{ src, want string }{
		"конфликт": {`
функция больший<T>(а: T, б: T): T
{
    вернуть а
}
функция главная
{
    переменная х = больший(1, 2.5)
}
`, "неоднозначен: Целое и Действительное"},
		"не из чего": {`
функция пустой<T>(): Список<T>
{
    вернуть новый Список<T>()
}
функция главная
{
    переменная сп = пустой()
}
`, "не удалось вывести параметр типа T"},
	}
	for name, c := range cases {
		t.Run(name, func(t *testing.T) {
			_, err := AnalyzeSource(t, c.src)
			if err == nil || !strings.Contains(err.Error(), c.want) {
				t.Fatalf("ожидалась ошибка с %q, получено %v", c.want, err)
			}
		})
	}
}

// Ограничение "T как Интерфейс" проверяется и у выведенного аргумента.
func TestInferGenericChecksConstraint(t *testing.T) {
	_, err := AnalyzeSource(t, `
интерфейс Звучащий
{
    издать_звук(): Строка
}
функция крикнуть<T как Звучащий>(x: T): Строка
{
    вернуть x.издать_звук()
}
функция главная
{
    переменная з = крикнуть(5)
}
`)
	if err == nil {
		t.Fatalf("ожидалась ошибка ограничения параметра типа")
	}
}
