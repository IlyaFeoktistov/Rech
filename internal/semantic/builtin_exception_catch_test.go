package semantic

import "testing"

// Встроенное исключение ловится по имени в функции, которую анализ
// проходит раньше первого "разобрать" (сама сущность регистрируется
// лениво).
func TestBuiltinExceptionCatchableByNameBeforeFirstUse(t *testing.T) {
	_, err := AnalyzeSource(t, `
сущность Точка
{
    имеет:
        публичный x: Целое
}

функция безопасно(действие: Вызываемый())
{
    попытаться {
        действие()
    } поймать(иск: ОшибкаРазбора) {
        вывести иск.сообщение
    }
}

функция главная
{
    безопасно(функция () {
        Точка т = разобрать JSON "{}" как Точка
    })
}
`)
	if err != nil {
		t.Fatalf("неожиданная ошибка: %v", err)
	}
}
