// handleSugarMethodNames - объединение всех имён методов из
// handleMethodSugar - быстрая проверка ДО анализа получателя (та же
// причина, что у dateTimeSugarMethodNames: подавляющее большинство вызовов
// методов не имеет отношения к этому сахару вовсе, разбирать тип получателя
// заранее незачем).
var handleSugarMethodNames = func() map[string]bool {
	names := map[string]bool{}
	for _, methods := range handleMethodSugar {
		for name := range methods {
			names[name] = true
		}
	}
	return names
}()

// maybeDesugarHandleMethod - вызывается из analyzeExpr/analyzeStmt ДО
// обычного analyzeMethodCallExpr, тем же контрактом, что и
// maybeDesugarDateTimeMethod: handled=false (без ошибки) - получатель не
// один из хендл-типов выше, или e.Method не одно из известных имён на ЭТОМ
// типе (в т.ч. одноимённый метод обычной пользовательской сущности) -
// вызывающая сторона идёт обычным путём.
func maybeDesugarHandleMethod(sc *ctx, e *ast.MethodCallExpr) (result ir.Expr, handled bool, err error) {
	if !handleSugarMethodNames[e.Method] {
		return nil, false, nil
	}
	receiver, err := analyzeExpr(sc, e.Receiver)
	if err != nil {
		return nil, false, nil
	}
	receiver = maybeUnwrapNarrowed(sc, receiver)
	methods, ok := handleMethodSugar[ir.TypeOf(receiver)]
	if !ok {
		return nil, false, nil
	}
	funcName, ok := methods[e.Method]
	if !ok {
		return nil, false, nil
	}
	call, cerr := analyzeCallExpr(sc, &ast.CallExpr{
		Callee: funcName,
		Args:   append([]ast.Expr{e.Receiver}, e.Args...),
		Line:   e.Line,
	})
	return call, true, cerr
}
