// Метод-стиль обёртки над builtin-функциями, чей первый параметр - уже
// существующий "хендл" (Файл/Сокет/БД/HTTP2Сессия/HTTP2Поток/Процесс) -
// "бд.запросить(...)"/"сокет.отправить(...)"/"файл.закрыть()" вместо
// "запросить(бд, ...)"/"отправить(сокет, ...)"/"закрыть(файл)". Пользователь
// явно попросил перевести накопившиеся такие функции в методы (бэклог,
// та же мотивация, что и у Carbon-методов "ДатаВремя", Шаг 124).
//
// Тем же принципом, что datetime_methods.go - ЧИСТЫЙ САХАР на этапе
// семантики, ни одного нового ir.Method: handleMethodSugar лишь
// перестраивает вызов метода в обычный ast.CallExpr к уже существующей
// свободной функции (получатель становится её первым аргументом) и отдаёт
// его в analyzeCallExpr - весь путь ленивой регистрации типов/сущностей,
// проверки аргументов, флагов cbackend (usesSockets/usesDB/usesHTTP2/...)
// отрабатывает СВОИМ обычным ходом, ни cbackend, ни interp не тронуты.
// Свободные функции продолжают работать буквально как раньше - это
// ДОПОЛНИТЕЛЬНЫЙ синтаксис, не замена.
