// Package semantic, продолжение - два найденных пробела (не было вообще
// никакого способа сделать ни то, ни другое):
//
//   - "спать_мс(миллисекунды: Целое)" - приостанавливает ТЕКУЩИЙ поток
//     (главный или "запустить"-поток - тот, что её вызвал) на заданное
//     число миллисекунд - раньше только хрупкий трюк через "Семафор.
//     захватить(таймаут_мс)" с всегда-пустым семафором, ловящий панику по
//     таймауту - неподходяще как обычный примитив паузы, не по смыслу
//     существования "Семафор" (admission control, не пауза).
//   - "выйти(код: Целое)" - немедленно завершает ВЕСЬ процесс с указанным
//     кодом возврата, из ЛЮБОЙ глубины вызовов, минуя "окончательно"/
//     "поймать" объемлющих "попытаться" (тот же принцип, что и exit() в
//     C/os.Exit в Go - НЕ то же самое, что "вернуть" из "главная", которая
//     не умеет отдавать код возврата вообще). Единственный способ дать
//     сценарию/оболочке, запустившей программу, отличить успех от ошибки
//     через код возврата ($?), не только через текст на stderr.
package semantic

import "github.com/IlyaFeoktistov/Rech/internal/ir"

func registerProcessFuncs(funcs map[string]funcSig) {
	funcs["спать_мс"] = funcSig{Params: []ir.Type{ir.TypeInt}}
	funcs["выйти"] = funcSig{Params: []ir.Type{ir.TypeInt}}
}
