package semantic

import (
	"strings"
	"testing"
)

const bareStructHeader = `структура Пара
{
    имеет:
        Целое  a
        Целое  b
        Строка метка = "пара"
}

структура Счёт
{
    имеет:
        Целое           номер
        приватное Целое остаток
}

сущность Узел
{
    имеет:
        Целое знач
}

функция сумма(п: Пара): Целое
{
    вернуть п.a + п.b
}

функция номер_счёта(с_: Счёт): Целое
{
    вернуть с_.номер
}
`

// TestAnalyzeBareStructFilledByFields - "Пара п" заполняется по полям:
// запись поля - не чтение, после записи всех полей без значения по
// умолчанию структура читается целиком; передача в функцию не стирает
// факт присвоенности.
func TestAnalyzeBareStructFilledByFields(t *testing.T) {
	_, err := AnalyzeSource(t, bareStructHeader+`
функция главная
{
    Пара п
    п.a = 1
    вывести п.a + длина_строки(п.метка)
    если п.a > 0 {
        п.b = 2
    } иначе {
        п.b = 3
    }
    вывести сумма(п)
    вывести сумма(п)
}
`)
	if err != nil {
		t.Fatalf("неожиданная ошибка: %v", err)
	}
}

func TestAnalyzeBareStructErrors(t *testing.T) {
	cases := []struct{ body, want string }{
		{"    Пара п\n    п.a = 1\n    вывести сумма(п)", "не заданы: b"},
		{"    Пара п\n    вывести п.b", "поле п.b читается до того, как ему присвоено значение"},
		{"    Пара п\n    если истина {\n        п.a = 1\n    }\n    вывести п.a", "поле п.a читается"},
		{"    Счёт с1\n    с1.номер = 1\n    вывести номер_счёта(с1)", "создайте структуру конструктором: с1 = новый Счёт(...)"},
		{"    Счёт с1\n    с1.остаток = 5", "приватное"},
		{"    Узел у\n    у.знач = 1", "сущность без значения: сначала создайте её (у = новый Узел(...))"},
	}
	for _, c := range cases {
		_, err := AnalyzeSource(t, bareStructHeader+"\nфункция главная\n{\n"+c.body+"\n}\n")
		if err == nil || !strings.Contains(err.Error(), c.want) {
			t.Errorf("%q: ожидалось %q, получено %v", c.body, c.want, err)
		}
	}
}
