func TestListElementPointerAccepted(t *testing.T) {
	cases := map[string]string{
		"добавить после последнего использования": `
функция главная
{
    Список<Целое> сп = новый Список<Целое>()
    сп.добавить(1)
    *Целое п = &сп[0]
    *п = 5
    сп.добавить(2)
}
`,
		"адрес взят заново после добавить": `
функция главная
{
    Список<Целое> сп = новый Список<Целое>()
    сп.добавить(1)
    *Целое п = &сп[0]
    сп.добавить(2)
    п = &сп[0]
    вывести *п
}
`,
		"свежий адрес на каждой итерации": `
функция главная
{
    Список<Целое> сп = [1, 2, 3]
    для i от 0 до 2 {
        *Целое п = &сп[i]
        *п = *п * 2
        сп.добавить(i)
    }
}
`,
		"аргумент вызова, свой список": `
функция изменить(п: *Целое)
{
    *п = 99
}

функция главная
{
    Список<Целое> сп = [1, 2]
    *Целое п = &сп[1]
    изменить(п)
    вывести ` + "`${*п} ${п == Ничто} ${п}\\n`" + `
}
`,
		"добавить только в ветке сп вернуть": `
функция ф(x: Логическое)
{
    Список<Целое> сп = [1]
    *Целое п = &сп[0]
    если x {
        сп.добавить(2)
        вернуть
    }
    вывести *п
}

функция главная
{
    ф(ложь)
}
`,
	}
	for name, src := range cases {
		t.Run(name, func(t *testing.T) {
			if _, err := AnalyzeSource(t, src); err != nil {
				t.Fatalf("неожиданная ошибка: %v", err)
			}
		})
	}
}

func TestListElementPointerRejected(t *testing.T) {
	cases := []struct {
		name, src, want string
	}{
		{"использование после добавить", `
функция главная
{
    Список<Целое> сп = [1]
    *Целое п = &сп[0]
    сп.добавить(2)
    вывести *п
}
`, "мог потерять силу: на строке 6"},
		{"обратное ребро цикла", `
функция главная
{
    Список<Целое> сп = [1]
    *Целое п = &сп[0]
    для i от 0 до 3 {
        вывести *п
        сп.добавить(i)
    }
}
`, "мог потерять силу"},
		{"условие пока пересчитывается", `
функция главная
{
    Список<Целое> сп = [1]
    *Целое п = &сп[0]
    пока *п < 10 {
        сп.добавить(1)
        *п = 20
    }
}
`, "мог потерять силу"},
		{"добавить в одной из веток", `
функция ф(x: Логическое)
{
    Список<Целое> сп = [1]
    *Целое п = &сп[0]
    если x {
        сп.добавить(2)
    }
    *п = 5
}

функция главная
{
    ф(истина)
}
`, "мог потерять силу"},
		{"общий список и вызов", `
функция другая()
{
}

функция ф(сп: Список<Целое>)
{
    *Целое п = &сп[0]
    другая()
    вывести *п
}

функция главная
{
    ф([1])
}
`, "вызов, который может изменить общий список"},
		{"список под другим именем", `
функция главная
{
    Список<Целое> сп = [1]
    *Целое п = &сп[0]
    Список<Целое> м = сп
    м.добавить(2)
    вывести *п
}
`, "передан дальше"},
		{"исключение посреди попытки", `
функция главная
{
    Список<Целое> сп = [1]
    *Целое п = &сп[0]
    попытаться {
        сп.добавить(2)
        вывести сп.получить(10)
    } поймать(о: Паника) {
        вывести *п
    }
}
`, "мог потерять силу"},
		{"вернуть", `
функция ф(сп: Список<Целое>): *Целое
{
    вернуть &сп[0]
}

функция главная
{
    ф([1])
}
`, "нельзя вернуть"},
		{"поле", `
сущность Хранитель
{
    имеет:
        публичный *Целое п

    конструктор()
    {
        этот.п = Ничто
    }
}

функция главная
{
    Список<Целое> сп = [1]
    Хранитель х = новый Хранитель()
    х.п = &сп[0]
}
`, "нельзя сохранить в поле"},
		{"коллекция", `
функция главная
{
    Список<Целое> сп = [1]
    Список<*Целое> указатели = новый Список<*Целое>()
    указатели.добавить(&сп[0])
}
`, "нельзя сохранить в коллекции"},
		{"захват лямбдой", `
функция главная
{
    Список<Целое> сп = [1]
    *Целое п = &сп[0]
    Вызываемый() ф = функция () {
        вывести *п
    }
    ф()
}
`, "нельзя захватить лямбдой"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			_, err := AnalyzeSource(t, tc.src)
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("ожидалась ошибка сп %q, получено: %v", tc.want, err)
			}
		})
	}
}
