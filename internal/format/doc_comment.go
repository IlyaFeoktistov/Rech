// canonicalizeDocComments приводит МНОГОСТРОЧНЫЙ doc-комментарий
// ("/** ... */", хотя бы один перенос строки внутри) к канонической форме
// Javadoc/JSDoc - "/**" само по себе на первой строке, каждая внутренняя
// строка - " * <текст>" (пустая - просто " *", без хвостового пробела),
// закрывающая "*/" - на своей собственной строке ("     */" получит
// правильный отступ позже, при пересчёте отступов - здесь важен только сам
// факт, что она отдельная строка):
//
//	/**
//	 * <текст 1>
//	 * <текст 2>
//	 */
//
// Пользователь попросил явно - "докблоки должны тоже сами
// форматироваться". ОДНОСТРОЧНЫЙ doc-комментарий ("/** Коротко. */", без
// единого переноса строки внутри - подавляющее большинство комментариев в
// этом репозитории) НЕ переоформляется - взрывать его в блок ради
// единообразия было бы масштабным переформатированием, которого не просили
// (см. package doc format.go про "не переформатировать походя").
//
// ЛЮБОЙ doc-комментарий (однострочный и многострочный) - если между его
// закрывающей "*/" и следующей непустой строкой есть пустые строки, они
// убираются: doc-комментарий обязан ПРИЛЕГАТЬ к тому, что документирует -
// парсер сам это терпит (consumeDoc, internal/parser/parser.go,
// skipNewlines - молча пропускает пустые строки между комментарием и
// объявлением), но пустая строка там - визуальный разрыв, которого автор
// почти наверняка не хотел (репортнуто пользователем - "` */`\n\nперечисление
// ...").
//
// Работает НАД ИСХОДНЫМ ТЕКСТОМ, ДО остальных проходов - заменяет диапазон
// физических строк, которые занимал токен (плюс любые пустые строки сразу
// после него), на новый (другой длины) набор строк; собственный отступ
// каждой новой строки не важен - computeLineDepths пересчитывает его с
// нуля позже, как и у остальных проходов этого пакета.
func canonicalizeDocComments(src string) (string, error) {
	toks, err := lexer.New(src).Tokenize()
	if err != nil {
		return "", err
	}

	normalized := strings.ReplaceAll(src, "\r\n", "\n")
	lines := strings.Split(normalized, "\n")

	type replacement struct {
		startLine, endLine int
		newLines           []string
	}
	var reps []replacement
	for _, t := range toks {
		if t.Type != lexer.DOC_COMMENT {
			continue
		}
		endLine := t.Line + strings.Count(t.Value, "\n")
		var newLines []string
		if strings.Contains(t.Value, "\n") {
			newLines = strings.Split(canonicalDocCommentText(t.Value), "\n")
		} else if endLine >= 1 && endLine <= len(lines) {
			newLines = []string{lines[endLine-1]} // однострочный - как есть
		}
		// Пустые строки СРАЗУ после "*/" - не настоящий разделитель (см.
		// package doc выше), поглощаются в "хвост" этой же замены, вместо
		// того чтобы попасть в вывод как есть.
		for endLine < len(lines) && strings.TrimSpace(lines[endLine]) == "" {
			endLine++
		}
		reps = append(reps, replacement{startLine: t.Line, endLine: endLine, newLines: newLines})
	}
	if len(reps) == 0 {
		return src, nil
	}

	var out []string
	cur := 1
	for _, r := range reps {
		for cur < r.startLine {
			out = append(out, lines[cur-1])
			cur++
		}
		out = append(out, r.newLines...)
		cur = r.endLine + 1
	}
	for cur <= len(lines) {
		out = append(out, lines[cur-1])
		cur++
	}
	return strings.Join(out, "\n") + "\n", nil
}

// listItemIndent - отступ ПРОДОЛЖЕНИЯ пункта списка ("- <текст>") - три
// пробела после "*" вместо обычного одного: " * " (сама метка "*" плюс
// один пробел, как у любой другой строки) + два пробела, РОВНО ширина
// "- " самой метки пункта - продолжение выравнивается точно под НАЧАЛОМ
// текста пункта, не под самой меткой. См. package doc canonicalDocCommentText
// про то, зачем это вообще нужно.
const listItemIndent = "  "

// hasListItemMarker - true, если content (уже нормализованная строка -
// см. normalizeDocCommentLine) НАЧИНАЕТСЯ с "- ", т.е. СИНТАКСИЧЕСКИ похожа
// на пункт списка через дефис. Одного этого недостаточно, чтобы считать
// строку настоящим пунктом списка - см. package doc canonicalDocCommentText
// про то, откуда берётся ложное срабатывание и как оно отсеивается.
func hasListItemMarker(content string) bool {
	return strings.HasPrefix(content, "- ")
}

// canonicalDocCommentText - полный текст док-комментария (включая "/**"/
// "*/" самих по себе) в канонической форме - см. package doc выше. value -
// сырой текст МЕЖДУ "/**" и "*/" (lexer.Token.Value, internal/lexer/
// lexer.go, readDocComment) - каждая его физическая строка (включая
// первую, идущую сразу за "/**" в исходнике, и последнюю, идущую сразу
// перед "*/") становится одной "содержательной" строкой блока, отбросив
// прежнее авторское оформление ("*"/пробелы в начале) и наложив заново
// единообразное.
//
// ИСКЛЮЧЕНИЕ из "все строки - один и тот же отступ" - продолжение пункта
// списка через дефис ("- <текст>", НАЙДЕНО пользователем вживую -
// examples/проекты/супервизор_процессов/исходников/главный.rech: при
// плоском отступе многострочный пункт списка перестаёт визуально
// отличаться от следующего пункта/обычного абзаца). Поскольку canon
// стирает АВТОРСКИЙ отступ полностью (normalizeDocCommentLine - "не
// важен", см. её package doc), принадлежность строки пункту списка
// восстанавливается ТОЛЬКО по содержимому, не по уцелевшим пробелам.
//
// "- " в начале строки САМО ПО СЕБЕ - ненадёжный признак: в прозе этого
// репозитория дефис с пробелами по бокам ("текст - текст") - обычный
// типографский знак (аналог тире), и когда автор переносит строку вручную
// ровно перед таким дефисом, тот оказывается в начале новой физической
// строки, ничем не отличаясь по виду от настоящего маркера списка (НАЙДЕНО
// живьём - examples/консоль/клавиши.rech, examples/изображения/
// примитивы.rech, examples/проекты/чат_сервер/исходники/клиент.rech,
// examples/сеть/grpc_привет.rech: без дополнительной проверки формататтер
// принимал такой перенос за начало пункта и ошибочно раздвигал остаток
// предложения). Настоящий пункт списка отличается КОНТЕКСТОМ, не своим
// собственным видом: либо это ПРОДОЛЖЕНИЕ уже открытого списка (предыдущая
// строка сама была пунктом/его продолжением), либо ему предшествует строка,
// оканчивающаяся на ":" - явное намерение автора перечислить пункты дальше.
// "- " без одного из этих двух условий - просто перенесённая пунктуация,
// рендерится как обычная строка (без list-отступа), список не открывается.
func canonicalDocCommentText(value string) string {
	raw := strings.Split(value, "\n")
	var b strings.Builder
	b.WriteString("/**\n")
	inListItem := false
	prevEndsWithColon := false
	for i, l := range raw {
		content := normalizeDocCommentLine(l)
		// Первая строка (сразу за "/**" в исходнике) и последняя (сразу
		// перед "*/") - если ПУСТА, это просто перенос строки у самого
		// разделителя, не настоящий пустой абзац содержимого - её незачем
		// рендерить отдельной " *" строкой (иначе появлялась бы лишняя
		// пустая строка, которой в исходнике не было). Пустая строка
		// СРЕДИ содержимого - настоящий разрыв абзаца автора, сохраняется.
		if content == "" && (i == 0 || i == len(raw)-1) {
			continue
		}
		if content == "" {
			b.WriteString(" *\n")
			inListItem = false
			prevEndsWithColon = false
			continue
		}
		wasInListItem := inListItem
		var indent bool
		if hasListItemMarker(content) {
			inListItem = wasInListItem || prevEndsWithColon
			indent = false
		} else {
			indent = wasInListItem
			inListItem = wasInListItem
		}

		b.WriteString(" * ")
		if indent {
			b.WriteString(listItemIndent)
		}
		b.WriteString(content)
		b.WriteString("\n")
		prevEndsWithColon = strings.HasSuffix(content, ":")
	}
	b.WriteString(" */")
	return b.String()
}

// normalizeDocCommentLine - "текст" одной строки doc-комментария, без
// прежнего авторского оформления: ведущие пробелы/табы, затем один ведущий
// "*" (если был) и ЛЮБЫЕ пробелы/табы сразу после него (если были) -
// отброшены; хвостовые пробелы - тоже. НАЙДЕННЫЙ БАГ - было
// strings.TrimPrefix(t[1:], " "), снимающее ровно ОДИН пробел после "*":
// автор, написавший ДВА (или больше) пробела после "*" (например, чтобы
// визуально продолжить отступ первой строки многострочного докблока -
// естественная, но не канон, привычка), получал один пробел ОБРАТНО, и
// он удваивался с добавляемым в canonicalDocCommentText "* " - итоговая
// строка так и оставалась с лишним пробелом, доклок выглядел
// "неотформатированным". strings.TrimLeft(t[1:], " \t") снимает ВСЕ,
// не только один. Работает одинаково для ЛЮБОЙ строки блока (первой/
// внутренней/последней) - у всех этот же смысл "что автор здесь
// написал", просто первая до этого стояла сразу за "/**" в исходнике, а
// не под своим собственным "*".
func normalizeDocCommentLine(l string) string {
	t := strings.TrimLeft(l, " \t")
	t = strings.TrimRight(t, " \t\r")
	if strings.HasPrefix(t, "*") {
		t = strings.TrimLeft(t[1:], " \t")
	}
	return t
}
