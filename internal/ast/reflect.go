package ast

// TypeOfExpr - "тип <Имя>" - дескриптор типа Имя, известного уже во время
// компиляции (аналог typeof(T) - в отличие от "значение.тип()", который
// читает дескриптор динамического значения в рантайме). TypeName - имя
// типа как есть в исходнике (примитив или сущность/структура,
// разрешается семантическим анализом), не выражение.
type TypeOfExpr struct {
	TypeName string
	Line     int
}

func (*TypeOfExpr) node() {}
func (*TypeOfExpr) expr() {}

// AsExpr - "<значение> как <Имя>" - разбоксирование "Значение" обратно к
// конкретному типу Имя (примитиву или сущности/структуре), проверяется в
// рантайме (несовпадение реального типа - паника). Отдельная от CastExpr
// конструкция - CastExpr ограничен фиксированным списком имён примитивов
// уже на этапе разбора (нельзя было бы отличить "(Тип) x" от "(x)" без
// такого списка), а целевой тип "как" может быть произвольной сущностью -
// "как" не участвует в этой неоднозначности (не начинается с "(").
type AsExpr struct {
	Value    Expr
	TypeName string
	Line     int
}

func (*AsExpr) node() {}
func (*AsExpr) expr() {}
