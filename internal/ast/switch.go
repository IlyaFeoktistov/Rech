package ast

// SwitchStmt соответствует конструкции:
//
//	выбрать <выражение>
//	{
//	    когда <значение>["|" <значение> ...]:
//	        <инструкции>
//	    иначе:
//	        <инструкции>
//	}
//
// Subject вычисляется РОВНО один раз (semantic analysis заводит под него
// внутреннюю временную переменную - см. internal/semantic/switch.go). Каждое
// значение в SwitchCase.Values - либо обычное выражение (сравнивается с
// Subject через "=="), либо голое имя типа сущности/интерфейса (сравнивается
// через "относится к" - ast.IsExpr) - какой из двух случаев, решает
// semantic analysis по контексту (объявлена ли переменная с таким именем в
// области видимости), не парсер, тем же принципом, что и у "относится
// к"/"наследует" - грамматика не размечает это явно. Ветки не проваливаются
// одна в другую (нет break, в отличие от switch/case в C) - десахарируется
// в цепочку "если/иначе если" (internal/semantic/switch.go), поэтому это
// свойство не требует отдельной поддержки в IR/backend'ах. Default
// (Default) необязателен - "выбрать" без совпавшей ветки и без "иначе"
// просто ничего не делает.
type SwitchStmt struct {
	Subject Expr
	Cases   []SwitchCase
	Default []Stmt
	Line    int
}

func (*SwitchStmt) node() {}
func (*SwitchStmt) stmt() {}

// SwitchCase - одна ветка "когда <значение>[|<значение>...]:" внутри
// SwitchStmt.
type SwitchCase struct {
	Values []Expr
	Body   []Stmt
	Line   int
}
