package ast

// GenericParam - один параметр типа в объявлении generic-сущности/функции -
// "T" или "T как Тип1|Тип2" (Constraints). "как" - тот же токен, что и в
// "использовать ... как ..." (переименование при импорте), в новой
// грамматической позиции - не отдельное ключевое слово.
//
// Constraints - список допустимых типов для конкретного аргумента этого
// параметра при инстанциации (nil - без ограничений, аргументом может
// быть любой тип). "|" разделяет альтернативы ВНУТРИ одного ограничения
// (тот же принцип, что и у "поймать(иск: Тип1|Тип2)"); "," на
// уровень выше разделяет РАЗНЫЕ параметры типа ("Тип<T как Число, U>") -
// не может использоваться и для альтернатив, и для разделения параметров
// одновременно, поэтому два разных разделителя. Аргумент удовлетворяет
// ограничению, если он равен одному из перечисленных типов (примитивы) или
// связан с одним из них наследованием/соответствием интерфейсу (сущности/
// интерфейсы) - та же проверка отношения, что и у "относится к"
// (internal/semantic, relatedForIsCheck), в направлении "аргумент ->
// ограничение".
type GenericParam struct {
	Name        string
	Constraints []string
	Line        int
}
