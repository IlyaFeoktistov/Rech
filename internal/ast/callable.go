package ast

// FuncRefExpr - "&имя" - ссылка на уже объявленную функцию как на значение
// типа "Вызываемый", без вызова.
type FuncRefExpr struct {
	Name string
	Line int
}

func (*FuncRefExpr) node() {}
func (*FuncRefExpr) expr() {}

// CaptureSpec - один элемент явного списка захвата лямбды ("[x, &y]", см.
// package doc LambdaExpr.Captures) - ByRef true у "&имя" (запись внутри
// тела видна снаружи, без ручного Указатель<T>), false у голого "имя"
// (копия значения на момент создания - то же правило, что у неявного
// захвата).
type CaptureSpec struct {
	Name  string
	ByRef bool
	Line  int
}

// LambdaExpr - функция без имени в позиции выражения:
//
//	функция(<парам>: <Тип>, ...): <ТипРезультата> { <тело> }
//	функция(<парам>: <Тип>, ...): <ТипРезультата> [x, &y] { <тело> }
//
// Та же форма параметров/тела, что и у именованной FunctionDecl (Params,
// ReturnType, Body), но без Name и без TypeParams - лямбда не может быть
// generic.
//
// HasCaptures - true, если явный список "[...]" присутствует в исходнике
// (даже пустой "[]" - лямбда, закрытая ото всех внешних переменных) - его
// ОТСУТСТВИЕ (обычная форма без "[...]", как раньше) сохраняет прежнее
// поведение: свободные переменные тела ищет семантический анализ сам
// (неявный захват, всегда по значению). Его ПРИСУТСТВИЕ, наоборот,
// заменяет неявный захват целиком (C++-стиль, согласовано с
// пользователем) - внутри тела видны РОВНО перечисленные имена, обращение
// к любой другой внешней переменной - ошибка компиляции, даже если она
// существует в объемлющей области видимости.
type LambdaExpr struct {
	Params      []Param
	ReturnType  string
	HasCaptures bool
	Captures    []CaptureSpec
	Body        []Stmt
	Line        int
}

func (*LambdaExpr) node() {}
func (*LambdaExpr) expr() {}
