// CStyleForStmt соответствует общему циклу:
//
//	для <init>; <условие>; <шаг> { <тело> }
//
// Обобщение ForStmt (диапазон "от...до") для случаев, где нужен
// произвольный шаг/направление/несколько условий - Init всегда объявляет
// переменную цикла заново в ЕЁ СОБСТВЕННОЙ области видимости (тем же
// принципом, что ForStmt.Var/ForEachStmt.Var - не требует слова
// "переменная", хотя оно тоже допустимо: "для переменная i = 0; ...").
// Post - произвольная инструкция (обычно присваивание/инкремент
// переменной цикла), исполняется ПОСЛЕ тела на каждой итерации, ПЕРЕД
// повторной проверкой Cond - ровно как в C.
//
// Все три секции необязательны и независимы друг от друга (как в C) -
// Init == nil/Cond == nil/Post == nil, если соответствующая секция пуста.
// "для ;; { <тело> }" - все три пустые, бесконечный цикл (Cond == nil
// равносильно "истина"), выйти из которого можно только через "прервать"
// (или "вернуть"/панику/исключение).
type CStyleForStmt struct {
	Init *VarDecl
	Cond Expr
	Post Stmt
	Body []Stmt
	Line int
}

func (*CStyleForStmt) node() {}
func (*CStyleForStmt) stmt() {}

