// AssertStmt соответствует инструкции проверки условия:
//
//	утверждать <условие>
//	утверждать <условие>, <сообщение>
//
// Cond должно быть типа Логическое (проверяется backend'ом, как и условие
// "если"/"пока"). Если во время исполнения Cond ложно - аварийное
// завершение процесса (сообщение на stderr, exit(1)), как и rech_panic у
// встроенных коллекций (docs/SPEC.md, раздел 8) - не выброс исключения,
// который пользовательский код мог бы перехватить "попытаться"/"поймать" -
// ложное "утверждать" сигнализирует ошибку в самой программе, а не
// ожидаемое исключительное состояние. Не привязано к тестам как отдельной
// концепции языка - обычная инструкция, доступная в любой функции/методе;
// "тестовый файл" - это соглашение имени файла на уровне CLI (`rech test`,
// ), не отдельный синтаксис.
//
// Message - необязательное (nil - его не было) выражение типа Строка после
// запятой (внятные сообщения о несовпадении) - дописано к
// стандартному "утверждение не выполнено (строка N)" через ": ", тот же
// принцип, что и второй, необязательный аргумент "t.Errorf"/"t.Fatalf" в Go
// (сообщение строит вызывающий код через обычную конкатенацию/касты, а не
// отдельный набор типизированных builtin-сравнений - никакой генерик-магии
// не потребовалось). Всё ещё "не отдельный синтаксис для тестов" - обычное
// необязательное второе выражение у уже существующей инструкции, годится в
// любой функции, не только в тестовом файле.
type AssertStmt struct {
	Cond    Expr
	Message Expr
	Line    int
}

func (*AssertStmt) node() {}
func (*AssertStmt) stmt() {}

