// VarDecl соответствует инструкции объявления переменной с инициализацией:
//
//	переменная <имя> = <выражение>
//
// Тип переменной не аннотируется явно - выводится из выражения-инициализатора
// (простой literal-based inference, шаг 1).
type VarDecl struct {
	Name string
	// Type - явная аннотация типа ("переменная а: ?Целое = Ничто"), "" -
	// без аннотации (обычный вывод из Value, как раньше). Нужна там, где
	// вывести тип из Value невозможно - у голого "Ничто" (nullable-тип
	// иначе неоткуда взять) и у пустого литерала списка "[]".
	Type  string
	Value Expr
	// IsStatic - объявлена как "статическая переменная имя = значение":
	// значение вычисляется и сохраняется РОВНО один раз за всё время
	// работы программы (при первом достижении этой инструкции), а не
	// заново при каждом входе в функцию/тело цикла - как "static" локальная
	// переменная в C. "переменная" - существительное женского рода, форма
	// модификатора здесь не согласуется с именем самой переменной (в
	// отличие от видимости поля) - всегда "статическая".
	IsStatic bool
	Line     int
}

func (*VarDecl) node() {}
func (*VarDecl) stmt() {}

// ConstDecl - "константа <имя> = <значение>" - как VarDecl, но повторное
// присваивание этому имени (Assign) - ошибка компиляции
// (internal/semantic), не времени выполнения; локальная/верхнеуровневая
// константа вычисляется и хранится тем же кодом, что и обычная переменная
// (internal/ir не отличает их вообще - см. package doc internal/semantic).
//
// Visibility осмыслена для константы внутри тела "сущность"
// (EntityDecl.Constants, "приватная"/"публичная"/"защищённая", согласуется
// со словом "константа" - женский род, единственное число, не с Name -
// имя константы обычно КАПС_ЛОКОМ и не является обычным существительным)
// И для константы уровня МОДУЛЯ (ast.Program.Consts, только
// "приватная"/"публичная" - без "защищённого", тем же принципом, что и у
// функций/сущностей на уровне модуля, internal/parser/modvisibility.go) -
// внутри "использовать" видит только публичную. У ЛОКАЛЬНОЙ константы
// (обычная инструкция внутри тела функции/метода, не Program.Consts)
// видимость не имеет смысла - парсер модификатор перед ней не принимает
// в этом контексте, Visibility всегда Public.
type ConstDecl struct {
	Name       string
	Value      Expr
	Visibility Visibility
	Line       int
	// Doc - текст doc-комментария ("/** ... */") прямо перед объявлением,
	// "" - его не было. Осмысленно только у константы уровня сущности
	// (EntityDecl.Constants) - см. ast.EntityDecl.Doc; у ConstDecl,
	// встреченного как обычная инструкция внутри тела функции/метода,
	// парсер его так же разбирает, но там он не несёт смысла (см.
	// EntityDecl.Doc про локальные переменные).
	Doc string
	// File - см. EntityDecl.File. Осмысленно только у константы уровня
	// модуля (ast.Program.Consts, см. ast.StampFile) - у константы уровня
	// сущности (EntityDecl.Constants) файл известен через саму EntityDecl,
	// у локальной (обычная инструкция внутри тела) - через File функции/
	// метода, в обоих случаях отдельное поле не нужно, остаётся "".
	File string
}

func (*ConstDecl) node() {}
func (*ConstDecl) stmt() {}

