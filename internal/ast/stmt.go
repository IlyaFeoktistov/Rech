// ExprStmt - вызов функции как самостоятельная инструкция (ради побочного
// эффекта, результат отбрасывается):
//
//	<имя>(<арг>, ...)
//
// Единственное выражение, которое в шаге 3 разрешено как самостоятельная
// инструкция, - вызов функции, отсюда явное поле Call вместо общего Expr:
// строгий и естественный вызов (docs/GRAMMAR_DRAFT.md) производят один и тот же
// CallExpr, а ExprStmt - только тонкая обёртка вокруг него для позиции
// инструкции.
// Ровно одно из Call/MethodCall заполнено - строгий вызов функции или
// вызов метода сущности (шаг 4.d) как самостоятельная инструкция.
type ExprStmt struct {
	Call       *CallExpr
	MethodCall *MethodCallExpr
	IncDec     *IncDecExpr
	Await      *AwaitExpr
	Line       int
}

func (*ExprStmt) node() {}
func (*ExprStmt) stmt() {}

// GerundStmt - деепричастный вызов с последующим блоком:
//
//	<деепричастие>(<арг>, ...)
//	    <инструкция>
//	    ...
//
// Callee - имя функции (лемма, не сама деепричастная форма - разрешается
// парсером через p.gerundWords, тем же принципом, что resolveDeclinedTypeRef
// разрешает объект "наследует"/"реализует" в лемму), Args - её позиционные
// аргументы (как у обычного вызова, не падежное сопоставление естественного
// вызова). Body - инструкции с бОльшим отступом, чем у самого Callee (по
// столбцу первого токена, тем же приёмом, что и member'ы "имеет:", см.
// internal/parser/gerund.go) - как минимум одна: пустого блока не бывает.
//
// Внутри Body неявно доступна переменная "результат" со значением вызова -
// функция обязана объявлять тип результата (semantic отклоняет иначе,
// internal/semantic/gerund.go); "результат" объявлена в СОБСТВЕННОЙ области
// видимости Body, поэтому вложенный GerundStmt внутри Body временно
// затеняет её на время своего собственного Body (тот же принцип, что и у
// вложенных если/пока).
type GerundStmt struct {
	Callee string
	Args   []Expr
	Body   []Stmt
	Line   int
}

func (*GerundStmt) node() {}
func (*GerundStmt) stmt() {}
