// Package ast описывает синтаксическое дерево Rech.
//
// Дерево не знает ничего о C, LLVM или интерпретаторе - оно описывает
// только структуру программы на русском языке. Backend'ы (cbackend и
// будущие interpreter/VM) читают это дерево и решают, во что его превратить.
// См. docs/ROADMAP.md, этап "IR": позже между AST и backend'ами появится
// отдельный слой IR, но интерфейс Stmt/Expr рассчитан так, чтобы это не
// потребовало переписывать парсер.
package ast

// Node - общий маркерный интерфейс всех узлов дерева.
type Node interface {
	node()
}

// Program - корень дерева: список объявленных функций и сущностей одного
// файла, плюс импорты из других файлов.
type Program struct {
	Functions   []*FunctionDecl
	Entities    []*EntityDecl
	Uses        []*UseDecl
	ExternFuncs []*ExternFuncDecl
	Enums       []*EnumDecl
	Interfaces  []*InterfaceDecl
}

func (*Program) node() {}

// UseDecl соответствует инструкции импорта:
//
//	использовать <имя> [как <псевдоним>], <имя> [как <псевдоним>], ... из "<путь>"
//
// Names - функции/сущности, объявленные в файле по Path (без расширения
// ".rech", разрешение пути - internal/module.Load). Проверка того, что
// каждое имя действительно объявлено в целевом файле, и что его псевдоним
// не конфликтует с уже занятым в текущем файле именем, - тоже
// internal/module, не парсер.
type UseDecl struct {
	Names []UseName
	Path  string
	Line  int
}

func (*UseDecl) node() {}

// UseName - одно импортируемое имя. Alias - имя, под которым Name доступно
// в текущем файле; Alias == Name, если "как <псевдоним>" не написано.
// Переименование при импорте - единственный способ ввести в файл два
// одноимённых (в исходных файлах) импорта одновременно, не смешиваясь
// друг с другом или с собственным именем текущего файла (docs/ROADMAP.md,
// Шаг 11, "Пространства имён" - квалификатор `Модуль.Имя` для этой же
// задачи обсуждался и отклонён как более сложное решение той же проблемы).
type UseName struct {
	Name  string
	Alias string
	Line  int
}

// ExternFuncDecl соответствует конструкции внешней C-функции (FFI):
//
//	внешняя функция <ИмяC> [как <Псевдоним>](<парам>: <Тип>, ...): <ТипВозврата>
//
// Объявление сигнатуры уже существующей C-функции без тела - реализация
// уже есть (libc/libm, которые компилятор и так безусловно линкует, см.
// internal/toolchain), нужно только описать её сигнатуру на границе с C
// ABI. CName - настоящее имя C-функции (так, как она объявлена в её
// собственном заголовке); Alias - имя, под которым функция доступна
// остальному коду Rech (Alias == CName, если "как <псевдоним>" не
// написано - тот же принцип переименования, что и у UseName). Ограничения
// этого среза (docs/ROADMAP.md, Шаг 7): нет "из библиотеки ..." - только
// то, что уже слинковано (libc/libm); типы параметров и результата -
// только Целое/Число/Строка/Логическое (backend, не парсер, отвергает
// сущности/generic-коллекции здесь).
type ExternFuncDecl struct {
	CName      string
	Alias      string
	Params     []Param
	ReturnType string // "" - функция ничего не возвращает (C void)
	Line       int
}

func (*ExternFuncDecl) node() {}

// EntityDecl соответствует конструкции:
//
//	сущность Имя
//	{
//		константа <имя> = <значение>
//		...
//		состояние <состояние1>, <состояние2>, ...
//	    имеет:
//	        поле: Тип
//	        ...
//	    метод(<парам>: <Тип>, ...): <ТипВозврата>
//	    {
//	        <тело>
//	    }
//	}
//
// ("класс" - синоним "сущность", docs/GRAMMAR.md).
type EntityDecl struct {
	Name string
	// IsStruct - объявлено словом "структура", а не "сущность"/"класс":
	// значение передаётся по значению (копия при переменной/присваивании/
	// параметре/поле/возврате - как сущность до перехода на ссылочную
	// семантику), а не по ссылке. Форма тела (поля/методы/состояния/
	// константы) у "структура" та же самая, отличие целиком в этом флаге.
	IsStruct bool
	// BaseName - имя сущности после "наследует", "" - нет базовой
	// сущности. Только у "сущность"/"класс" (не "структура" - см.
	// IsStruct - наследование/интерфейсы ограничены ссылочными типами,
	// проверяется семантическим анализом, не парсером).
	BaseName string
	// Interfaces - имена интерфейсов после "реализует", через запятую, в
	// порядке объявления - nil, если слова "реализует" не было.
	Interfaces []string
	Constants  []*ConstDecl
	States     []StateDecl
	Fields     []Field
	Methods    []*MethodDecl
	// Ctor - явное тело конструктора, nil - нет ("новый Тип(...)" остаётся
	// неявным позиционным/именованным присваиванием полей). Только у
	// "сущность"/"класс" (не "структура" - см. IsStruct), как и
	// BaseName/Interfaces.
	Ctor *ConstructorDecl
	// TypeParams - параметры типа после имени сущности ("Коробка<T>") -
	// nil, если сущность не generic. Ограничено сущностями без
	// наследования/интерфейсов (BaseName/Interfaces пустые) - см. package
	// doc GenericParam.
	TypeParams []GenericParam
	Line       int
	// File - путь исходного файла, из которого объявлена сущность (методы/
	// конструктор объявлены внутри её же тела, отдельного File для них не
	// нужно) - проставляется НЕ парсером (он не знает свой путь), а
	// вызывающим кодом сразу после разбора файла (internal/compiler.
	// parseFileRaw, internal/module.loader.load) - нужен отладчику
	// (internal/debugger) для сопоставления точки останова "файл:строка" с
	// конкретной функцией/методом/конструктором в объединённой программе
	// (после module.Link несколько файлов сливаются в одну *ast.Program,
	// без File по одному Line нельзя было бы понять, к какому файлу он
	// относится).
	File string
	// Doc - текст doc-комментария ("/** ... */") прямо перед объявлением
	// сущности, "" - его не было. Парсер копирует его как есть (без
	// обрезки отступов построчно) - internal/lsp форматирует при показе
	// (hover), сам компилятор его нигде не проверяет и не использует.
	// Функция/метод/сущность/поле/константа - единственные объявления,
	// которые его несут (см. одноимённые поля Doc у FunctionDecl/
	// MethodDecl/Field/ConstDecl) - локальные переменные внутри тела
	// функции/метода doc-комментарии не несут, у них нет устойчивого
	// "API", который имело бы смысл документировать отдельно от места
	// использования.
	Doc string
}

func (*EntityDecl) node() {}

// Field - одно поле сущности, объявленное под "имеет:". Type - имя типа,
// как и у Param (проверка допустимости - в backend'е). Visibility -
// необязательный модификатор "приватный"/"публичный"/"защищённый"
// (согласованный по роду с Name), написанный перед именем поля; без
// модификатора поле публичное (Visibility == Public).
type Field struct {
	Name       string
	Type       string
	Visibility Visibility
	Line       int
	// Doc - текст doc-комментария ("/** ... */") прямо перед объявлением
	// поля, "" - его не было. См. package doc EntityDecl.Doc.
	Doc string
}

// StateDecl - одно состояние, объявленное под "состояние:" (упрощённая
// версия, без падежного согласования - см. docs/GRAMMAR.md). Name -
// краткая форма причастия/прилагательного ровно как написана в объявлении
// ("авторизован") - именно её должна повторить инструкция "становится
// <Name>" (BecomeStmt). TypeName - производный тип, синтезированный
// парсером при разборе сущности (полная форма по роду сущности + имя
// сущности, "АвторизованныйПользователь") - готовая строка, как и у
// generic-инстанциаций ("Список<Целое>"), backend не занимается
// морфологией, только регистрирует TypeName как синоним типа сущности.
type StateDecl struct {
	Name     string
	TypeName string
	Line     int
}

// EnumDecl - "перечисление <Имя> { Член1, Член2 = число, ... }" -
// верхнеуровневое объявление, как EntityDecl. Члены не несут собственного
// типа (internal/semantic резолвит "Имя.Член" прямо в ir.IntLiteral во
// время анализа - никакой отдельный ir.Kind/entitySig этой конструкции не
// нужен, перечисление логически хранится как Целое):
// доступ - тем же синтаксисом, что и FieldAccess ("Имя.Член"), парсер не
// различает их вообще (расширять грамматику не нужно) - разница видна
// только семантическому анализу (получатель - объявленная переменная или
// имя перечисления).
type EnumDecl struct {
	Name    string
	Members []EnumMember
	Line    int
}

func (*EnumDecl) node() {}

// EnumMember - один член перечисления - Value уже вычислено парсером
// (0 у первого члена без явного "= <целое>", дальше - предыдущее значение
// + 1, как в C) - к моменту, когда до этого дойдёт internal/semantic,
// разница между явным и автоматическим значением уже не имеет значения.
type EnumMember struct {
	Name  string
	Value int64
	Line  int
}

// MethodDecl - метод сущности: как FunctionDecl (те же параметры/тип
// результата/тело), но без ключевого слова "функция" - объявляется прямо в
// теле сущности (docs/GRAMMAR.md, "method"). Внутри тела метода доступно
// зарезервированное слово "этот" (ThisExpr) - ссылка на объект, у которого
// вызван метод.
// Visibility - необязательный модификатор
// "приватный"/"публичный"/"защищённый" перед именем метода. У метода нет
// рода (называется глаголом), поэтому в отличие от Field.Visibility
// модификатор метода не согласуется - допустима только форма мужского
// рода ("приватный", не "приватная"/"приватное"/"приватные"), проверяется
// парсером. Без модификатора метод публичный (Visibility == Public).
type MethodDecl struct {
	Name   string
	Params []Param
	// ReturnType - имя типа результата, "" - не объявлен. Не читается,
	// когда SelfReturn - true (см. SelfReturn).
	ReturnType string
	// SelfReturn - тип результата объявлен как "этот" ("имя(...): этот"),
	// а не именем конкретного типа - ковариантный "self type" (как `this`
	// в TypeScript/`Self` в Swift): результат типизируется КОНКРЕТНЫМ
	// статическим типом получателя в месте вызова, а не тем типом, который
	// объявляет метод - нужен для цепочек вызовов ("fluent"-методов) через
	// наследование, где переопределённый в подклассе метод не обязателен,
	// а базовый должен возвращать именно подкласс, если вызван через него.
	// Разрешается в internal/semantic - каждая сущность/интерфейс
	// собственноручно резолвит "этот" в EntityType(себя)/InterfaceType(себя)
	// при сборе своей сигнатуры (см. package doc internal/semantic/
	// inheritance.go, applyInheritance) - НЕ наследуется как единое
	// конкретное значение, только как сам факт "тип результата - self".
	SelfReturn bool
	Body       []Stmt
	Visibility Visibility
	Line       int
	// Doc - текст doc-комментария ("/** ... */") прямо перед объявлением
	// метода, "" - его не было. См. package doc EntityDecl.Doc.
	Doc string
}

// FunctionDecl соответствует конструкции:
//
//	функция <имя>(<парам>: <Тип>, ...): <ТипВозврата>
//	{
//	    <тело>
//	}
//
// Параметры и тип возврата необязательны (Params == nil, ReturnType == "").
type FunctionDecl struct {
	Name       string
	Params     []Param
	ReturnType string // "" - тип результата не объявлен
	Body       []Stmt
	// TypeParams - параметры типа после имени функции ("первый<T>") - nil,
	// если функция не generic. См. package doc GenericParam.
	TypeParams []GenericParam
	Line       int
	// File - см. EntityDecl.File.
	File string
	// Doc - текст doc-комментария ("/** ... */") прямо перед объявлением
	// функции, "" - его не было. См. package doc EntityDecl.Doc.
	Doc string
}

func (*FunctionDecl) node() {}

// Param - один параметр функции. Name - отображаемое имя (используется в
// теле функции). CaseWord - падежная роль параметра при естественном
// вызове (одно из кто/кого/кому/кем/где/что, см.
// internal/morph.CaseOfParamName) или "" - без падежной роли, тогда
// параметр доступен только позиционно (естественный вызов заполняет такие
// параметры "по остатку" - см. docs/SPEC.md, "Вызов функции (естественный
// синтаксис)"). Name == CaseWord, когда параметр объявлен одним словом
// (`кого: Тип`, исторический и по-прежнему основной случай) - падежное
// слово тогда одновременно и имя, и роль; двусловная форма (`кого
// пользователь: Тип`) даёт отдельное отображаемое имя при той же роли.
// Type - имя типа (проверка допустимости - в backend'е, как и для типа
// переменных, а не здесь, см. заголовочный комментарий cbackend/generator.go).
type Param struct {
	Name     string
	CaseWord string
	Type     string
	Line     int
}

// Stmt - инструкция внутри тела функции.
