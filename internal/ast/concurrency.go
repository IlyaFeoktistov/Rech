package ast

// LaunchExpr соответствует выражению:
//
//	запустить <имя>(<арг>, ...)
//
// Call - строгий вызов обычной (не встроенной, не внешней, не метода)
// функции программы - запускает её тело в отдельном потоке ОС и
// немедленно возвращает значение-дескриптор ("Задача"), не дожидаясь
// завершения. Ограничено обычными функциями сознательно: у метода есть
// неявный получатель ("этот"), совместное владение которым между потоками
// требует отдельной проработки; у встроенной/внешней функции нет
// гарантии потокобезопасности (общее состояние библиотеки C).
type LaunchExpr struct {
	Call *CallExpr
	Line int
}

func (*LaunchExpr) node() {}
func (*LaunchExpr) expr() {}

// CoroLaunchExpr соответствует выражению:
//
//	поручить <асинхронная функция>(<арг>, ...)
//
// Фоновый запуск функции, объявленной "асинхронная" (см. FunctionDecl.
// IsAsync), на лёгком планировщике корутин (Шаг 132) -
// НЕМЕДЛЕННО возвращает значение-дескриптор ("Задача", тот же
// пользовательский тип, что и у LaunchExpr - разница в реализации под
// капотом не видна Rech-коду), не дожидаясь завершения и НЕ блокируя
// текущий контекст выполнения вовсе (в отличие от сахара "дождаться
// <асинхронная функция>()" - тот атомарен: спавнит и сразу дожидается).
// Именно это и даёт настоящую конкурентность нескольких соединений на
// одном планировщике - вызывающий код (например, accept-цикл сервера)
// продолжает работу сразу же, не дожидаясь обработки текущего.
// Ограничено асинхронными функциями (не любой обычной функцией, в
// отличие от "запустить") - семантика (internal/semantic/concurrency.go)
// отклоняет цель без "асинхронная".
type CoroLaunchExpr struct {
	Call *CallExpr
	Line int
}

func (*CoroLaunchExpr) node() {}
func (*CoroLaunchExpr) expr() {}

// AwaitExpr соответствует выражению:
//
//	дождаться <выражение>
//
// Блокирует текущий поток до завершения задачи Task (значения,
// полученного через LaunchExpr) - если обёрнутая функция объявляет тип
// результата, значение доступно как результат AwaitExpr; необработанное
// внутри задачи исключение выбрасывается заново здесь же, в потоке,
// вызвавшем "дождаться" - перехватывается обычным "попытаться"/"поймать"
// вокруг него, тем же принципом, что и исключение из обычного вызова.
type AwaitExpr struct {
	Task Expr
	Line int
}

func (*AwaitExpr) node() {}
func (*AwaitExpr) expr() {}
