package ast

// ConstructorDecl соответствует явному телу конструктора сущности:
//
//	конструктор(<парам>: <Тип>, ...) { <тело> }
//
// Необязателен - сущность без него сохраняет прежнее поведение "новый
// Тип(значение1, ...)" (позиционное/именованное присваивание полей один-в-
// один, EntityDecl.Ctor == nil). Если объявлен - "новый Тип(...)" вызывает
// его вместо неявного присваивания: Params - собственный список параметров
// конструктора (не обязан совпадать с полями сущности ни числом, ни
// порядком), Body - обычные инструкции, которые сами присваивают поля через
// "этот.поле = значение". Ограничено ссылочными типами (не "структура" -
// см. EntityDecl.IsStruct, парсер отказывает так же, как и "наследует"/
// "реализует").
type ConstructorDecl struct {
	Params []Param
	Body   []Stmt
	Line   int
}

// ParentCallStmt соответствует инструкции:
//
//	родитель(<арг>, ...)
//
// Вызывает конструктор БАЗОВОЙ сущности целиком (включая его тело) на том
// же самом объекте - валидно только первой инструкцией в теле
// ConstructorDecl сущности, у которой есть "наследует", и только если у
// самой базовой сущности есть собственный явный конструктор (иначе вызывать
// нечего - унаследованные поля можно присвоить и напрямую через
// "этот.поле = значение"). Структурные ограничения (позиция, наличие
// базового конструктора) проверяются семантическим анализом, не парсером.
type ParentCallStmt struct {
	Args []Expr
	Line int
}

func (*ParentCallStmt) node() {}
func (*ParentCallStmt) stmt() {}
