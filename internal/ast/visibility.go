package ast

// Visibility - видимость поля/метода/константы сущности: три уровня.
// Public - видно отовсюду. Private - только из методов самой сущности.
// Protected - из методов самой сущности и любой сущности, которая её
// наследует (транзитивно) - имеет практический смысл только у сущности,
// участвующей в наследовании, но парсер это не проверяет (проверяется на
// этапе семантического анализа, как и остальные ограничения типов).
type Visibility int

const (
	Public Visibility = iota
	Private
	Protected
)
