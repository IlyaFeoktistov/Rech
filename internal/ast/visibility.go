package ast

// Visibility - видимость поля/метода/константы сущности ИЛИ объявления
// верхнего уровня файла (internal/parser/modvisibility.go) - общий тип на
// оба среза, хотя ни один уровень не встречается в обоих сразу (Protected -
// только у членов сущности, Internal - только у верхнего уровня файла, см.
// их описания). Public - видно отовсюду. Private - только из методов самой
// сущности (у члена сущности) или только из самого файла (у объявления
// верхнего уровня, internal/module/module.go). Protected - из методов самой
// сущности и любой сущности, которая её наследует (транзитивно) - имеет
// практический смысл только у сущности, участвующей в наследовании, но
// парсер это не проверяет (проверяется на этапе семантического анализа, как
// и остальные ограничения типов). Internal - видно любому файлу ТОГО ЖЕ
// .rechproj-проекта (обычный импорт, "@путь"), но не файлу, который дошёл
// до этого объявления, ПЕРЕСЕКАЯ границу зависимости ("использовать ... из
// "имя_зависимости/путь"") - internal/module/module.go, load (crossedInto).
type Visibility int

const (
	Public Visibility = iota
	Private
	Protected
	Internal
)
