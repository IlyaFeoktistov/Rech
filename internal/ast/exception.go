package ast

// ThrowStmt соответствует инструкции:
//
//	выбросить <выражение>
//
// Value должен вычисляться в значение сущности "Исключение" или наследника
// (проверяется семантическим анализом) - нелокальный выход из текущей
// точки исполнения до ближайшего охватывающего "попытаться", тип которого
// у поймать(...) соответствует фактическому типу исключения, либо до конца
// программы, если такого нет.
type ThrowStmt struct {
	Value Expr
	Line  int
}

func (*ThrowStmt) node() {}
func (*ThrowStmt) stmt() {}

// TryStmt соответствует конструкции:
//
//	попытаться {
//	    <тело>
//	} поймать(<имя>: <Тип> [ "|" <Тип> ...]) {
//	    <обработчик>
//	}
//
// Единственный "поймать" (не цепочка, как если/иначе если) - тип
// перехватываемого исключения указывается как перечисление через "|" прямо
// в одном поймать(...), различать несколько типов внутри обработчика (если
// нужно) - через "относится к" (IsExpr), опираясь на уже существующую
// полиморфную диспетчеризацию методов, а не на отдельный синтаксис "поймать
// ... поймать ...". CatchTypes - имена сущностей (все обязаны быть
// "Исключение" или наследником, проверяется семантическим анализом), CatchVar
// - имя, под которым перехваченное исключение доступно в CatchBody.
type TryStmt struct {
	Body       []Stmt
	CatchVar   string
	CatchTypes []string
	CatchBody  []Stmt
	Line       int
}

func (*TryStmt) node() {}
func (*TryStmt) stmt() {}

// IsExpr соответствует выражению:
//
//	<выражение> относится к <Тип>
//
// Логическая проверка фактического (времени исполнения) типа значения
// Value против Target - не только для исключений: любая сущность/
// интерфейс, связанные наследованием (Target - предок/потомок статического
// типа Value) или соответствием интерфейсу. "к" - предлог дательного
// падежа ("относиться к кому/чему"), поэтому Target разбирается через
// склонение, как и объект после "наследует"/"реализует" (см.
// internal/parser.resolveDeclinedTypeRef), а не берётся словарной формой.
type IsExpr struct {
	Value  Expr
	Target string
	Line   int
}

func (*IsExpr) node() {}
func (*IsExpr) expr() {}
