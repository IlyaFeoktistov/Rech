package ast

// ThrowStmt соответствует инструкции:
//
//	выбросить <выражение>
//
// Value должен вычисляться в значение сущности "Исключение" или наследника
// (проверяется семантическим анализом) - нелокальный выход из текущей
// точки исполнения до ближайшего охватывающего "попытаться", тип которого
// у поймать(...) соответствует фактическому типу исключения, либо до конца
// программы, если такого нет.
type ThrowStmt struct {
	Value Expr
	Line  int
}

func (*ThrowStmt) node() {}
func (*ThrowStmt) stmt() {}

// TryStmt соответствует конструкции:
//
//	попытаться {
//	    <тело>
//	} поймать(<имя1>: <Тип> [ "|" <Тип> ...]) {
//	    <обработчик1>
//	} поймать(<имя2>: <Тип> ...) {
//	    <обработчик2>
//	} окончательно {
//	    <блок, который выполняется ВСЕГДА последним>
//	}
//
// Несколько "поймать" подряд (цепочка, как несколько "если"/"иначе если") -
// пробуются по порядку, первое совпадение отрабатывает, ни одно не
// подошло - исключение/паника пробрасывается дальше как обычно.
// internal/parser.parseTryStmt строит из цепочки ВЛОЖЕННЫЕ узлы TryStmt
// (первый написанный поймать - самый внутренний, последний - самый внешний) -
// этот тип несёт РОВНО ОДИН поймать (как и раньше, до цепочек); "относится
// к" (IsExpr) внутри одного обработчика по-прежнему различает конкретные
// типы, если нужно различать несколько типов, перечисленных через "|" в
// ОДНОМ поймать. CatchTypes - имена сущностей (все обязаны быть
// "Исключение" или наследником, проверяется семантическим анализом), CatchVar
// - имя, под которым перехваченное исключение доступно в CatchBody.
//
// CatchTypes - имена сущностей: "Исключение"/"Паника" или их наследники
// (проверяется семантическим анализом); могут смешивать обе иерархии.
//
// NoCatch - у "попытаться" вообще нет ни одного "поймать" (только
// "окончательно" - "попытаться { ... } окончательно { ... }", валидный
// голый try/finally без обработки ошибок) - CatchVar/CatchTypes/CatchBody
// не имеют смысла в этом случае (парсер их не заполняет).
//
// Finally - "окончательно { ... }", если он присутствовал - непусто ТОЛЬКО
// у самого ВНЕШНЕГО узла цепочки (последнего написанного "поймать" или,
// если "поймать" не было вовсе, самого "попытаться" - NoCatch true):
// исполняется ровно один раз после всей конструкции целиком - при обычном
// завершении тела, после того как какой-то из "поймать" отработал, и даже
// если ни один "поймать" не подошёл (перед тем как пробросить дальше) - см.
// internal/backend/cbackend/exceptions.go, generateIRTryWithFinallyStmt;
// internal/interp/exception.go, execTryWithFinally. Собственной CatchVar/
// доступа к пойманному значению внутри Finally нет - он не привязан ни к
// какому конкретному "поймать" (могло не сработать ни одно).
type TryStmt struct {
	Body       []Stmt
	CatchVar   string
	CatchTypes []string
	CatchBody  []Stmt
	NoCatch    bool
	Finally    []Stmt
	Line       int
}

func (*TryStmt) node() {}
func (*TryStmt) stmt() {}

// IsExpr соответствует выражению:
//
//	<выражение> относится к <Тип>
//
// Логическая проверка фактического (времени исполнения) типа значения
// Value против Target - не только для исключений: любая сущность/
// интерфейс, связанные наследованием (Target - предок/потомок статического
// типа Value) или соответствием интерфейсу. "к" грамматически требует
// дательного падежа ("относиться к кому/чему"), но, в отличие от объекта
// после "наследует"/"реализует" (internal/parser.resolveDeclinedTypeRef),
// Target берётся словарной формой как написано, без склонения - курируемый
// классификатор Фазы A слепо склоняет хвост составного имени как одно
// простое слово (docs/GRAMMAR_DRAFT.md, "Открытый вопрос: склонение составных
// имён").
type IsExpr struct {
	Value  Expr
	Target string
	Line   int
}

func (*IsExpr) node() {}
func (*IsExpr) expr() {}
