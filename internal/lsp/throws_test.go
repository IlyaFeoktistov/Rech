func throwsHover(t *testing.T, d *doc, name string) string {
	t.Helper()
	text, ok := d.hoverBareName(name, 1)
	if !ok {
		t.Fatalf("нет hover для %q", name)
	}
	return text
}

func TestHoverShowsThrownTypes(t *testing.T) {
	d := newDoc("test://a.rech", throwsTestSrc)
	if d.irProg == nil {
		t.Fatalf("документ не разобрался")
	}
	cases := map[string]string{
		"загрузить":     "Исключения: `ОшибкаФайла`",
		"обёртка":       "Исключения: `ОшибкаФайла`",
		"по_кругу":      "Исключения: `ОшибкаОплаты`",
		"разбор":        "Исключения: `ОшибкаРазбора`",
		"только_оплата": "Исключения: `ОшибкаФайла`\n\nПаники: `ВыходЗаГраницы`",
		"Касса":         "Исключения: `ОшибкаФайла`",
		"открыть":       "Исключения: `ОшибкаФайла`",
		"расшифровать":  "Исключения: `ОшибкаКриптографии`, `ОшибкаРазбора`",
		"подстрока":     "Паники: `Паника`",
	}
	for name, want := range cases {
		if got := throwsHover(t, d, name); !strings.HasSuffix(got, want) {
			t.Errorf("%s: ожидался хвост %q, получено %q", name, want, got)
		}
	}
	for _, name := range []string{"безопасно", "главная", "в_задаче"} {
		if got := throwsHover(t, d, name); strings.Contains(got, "Исключения:") || strings.Contains(got, "Паники:") {
			t.Errorf("%s: ничего не бросает, получено %q", name, got)
		}
	}
}

func TestHoverMethodShowsThrownTypes(t *testing.T) {
	d := newDoc("test://a.rech", throwsTestSrc)
	text, ok := d.hoverMember(d.entities["Касса"], "оплатить")
	if !ok {
		t.Fatal("нет hover для Касса.оплатить")
	}
	if want := "Исключения: `ОшибкаОплаты`\n\nПаники: `ВыходЗаГраницы`"; !strings.HasSuffix(text, want) {
		t.Fatalf("ожидался хвост %q, получено %q", want, text)
	}
}

func TestHoverCollectionMethodShowsPanic(t *testing.T) {
	text, ok := hoverGenericCollectionMember("Словарь<Строка, Целое>", "получить")
	if !ok || !strings.HasSuffix(text, "Паники: `КлючНеНайден`") {
		t.Fatalf("ожидалась паника КлючНеНайден, получено %q (%v)", text, ok)
	}
}
