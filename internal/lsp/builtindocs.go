// kindRechName - имя типа Rech, соответствующее internal/builtins.Kind -
// используется только для сборки сигнатуры в hover, не решение о типах
// самого языка (то - internal/semantic.builtinKindTypes).
func kindRechName(k builtins.Kind) string {
	switch k {
	case builtins.KindInt:
		return "Целое"
	case builtins.KindFloat:
		return "Действительное"
	case builtins.KindString:
		return "Строка"
	case builtins.KindBool:
		return "Логическое"
	case builtins.KindFile:
		return "Файл"
	case builtins.KindSocket:
		return "Сокет"
	default:
		return "?"
	}
}

// builtinFuncSignature строит "имя(Тип, ...): ТипРезультата" по
// internal/builtins.Func - параметры без имён (в отличие от
// functionSignature для пользовательских функций - builtins.Func их не
// несёт, только Kind).
func builtinFuncSignature(f builtins.Func) string {
	parts := make([]string, len(f.Params))
	for i, k := range f.Params {
		parts[i] = kindRechName(k)
	}
	sig := fmt.Sprintf("%s(%s)", f.Name, strings.Join(parts, ", "))
	if f.HasReturn {
		sig += ": " + kindRechName(f.ReturnKind)
	}
	return sig
}

// hoverBuiltinFunc - hover для встроенной функции (не объявленной в
// документе) по имени - "", false, если name не встроенная функция.
func hoverBuiltinFunc(name string) (string, bool) {
	sig, doc, ok := builtinFuncHoverParts(name)
	if !ok {
		return "", false
	}
	block := codeBlock(sig)
	if doc != "" {
		block += "\n\n" + doc
	}
	return withThrows(block, describeBuiltinThrows(name)), true
}

// builtinFuncHoverParts - сигнатура встроенной функции name и её
// описание (может быть пустым) - общая часть hover функции и hover метода-
// сахара над ней (sugarhover.go).
//
// reservedFuncSignatures несёт СИГНАТУРУ И ОПИСАНИЕ вместе через " — " -
// в код-блок hover идёт только сигнатура, описание - обычным markdown под
// ним: целиком в код-блоке редактор подсвечивал бы прозу описания как код
// Rech (любое совпадение с ключевым словом - "для", "если", "новый").
func builtinFuncHoverParts(name string) (sig, doc string, ok bool) {
	if f, ok := builtins.ByName(name); ok {
		return builtinFuncSignature(f), builtinFuncShortDoc[name], true
	}
	if full, ok := reservedFuncSignatures[name]; ok {
		sig, doc, _ := strings.Cut(full, " — ")
		return sig, doc, true
	}
	return "", "", false
}
