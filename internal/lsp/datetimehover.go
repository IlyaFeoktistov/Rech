// hoverDateTimeMethod - hover на методе "ДатаВремя" ("д.добавить_дни(1)").
func hoverDateTimeMethod(recv ir.Type, method string) (string, bool) {
	if recv != ir.EntityType("ДатаВремя") {
		return "", false
	}
	doc, ok := dateTimeMethodDocs[method]
	if !ok {
		return "", false
	}
	return withDoc(codeBlock("ДатаВремя."+doc[0]), doc[1]), true
}
