package lsp

import (
	"strings"
	"testing"
)

const docHoverSrc = `
/** Фигура на плоскости. */
интерфейс Фигура
{
    /** Площадь фигуры. */
    площадь(): Действительное
}

/** Квадрат. */
сущность Квадрат реализует Фигуру
{
    имеет:
        /** Длина стороны. */
        сторона: Действительное

    конструктор(сторона: Действительное)
    {
        этот.сторона = сторона
    }

    публичный площадь(): Действительное
    {
        вернуть этот.сторона * этот.сторона
    }
}

/** Основные цвета. */
перечисление Цвет { Красный, Зелёный }

функция главная
{
    /** Сколько раз повторить. */
    переменная повторов = 3
    /** Верхняя граница. */
    константа ПРЕДЕЛ = 10
    Фигура ф = новый Квадрат(2.0)
    вывести ф.площадь()
    вывести повторов + ПРЕДЕЛ
    вывести Цвет.Красный
}
`

// TestHoverShowsDocOfEveryDeclarationKind - doc-комментарий виден в hover у
// локальной переменной и константы, интерфейса и его метода, перечисления,
// поля сущности.
func TestHoverShowsDocOfEveryDeclarationKind(t *testing.T) {
	d := newDoc("test://a.rech", docHoverSrc)
	if d.irProg == nil {
		t.Fatalf("документ не разобрался: %+v", d.diagnostics)
	}
	cases := []struct{ lineText, word, want string }{
		{"вывести повторов + ПРЕДЕЛ", "повторов", "Сколько раз повторить."},
		{"вывести повторов + ПРЕДЕЛ", "ПРЕДЕЛ", "Верхняя граница."},
		{"вывести повторов + ПРЕДЕЛ", "ПРЕДЕЛ", "константа ПРЕДЕЛ"},
		{"Фигура ф = новый", "Фигура", "Фигура на плоскости."},
		{"вывести ф.площадь()", "площадь", "Площадь фигуры."},
		{"вывести Цвет.Красный", "Цвет", "Основные цвета."},
		{"вернуть этот.сторона", "сторона", "Длина стороны."},
	}
	for _, c := range cases {
		text, ok := hoverAt(t, d, docHoverSrc, c.lineText, c.word)
		if !ok || !strings.Contains(text, c.want) {
			t.Errorf("hover %q в строке %q: ожидалось %q, получено %q", c.word, c.lineText, c.want, text)
		}
	}
}
