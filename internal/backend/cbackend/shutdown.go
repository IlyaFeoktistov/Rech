package cbackend

// shutdownFlagCode - "запрошена_остановка(): Логическое" - взводится ОДИН
// раз, первым же SIGINT/SIGTERM. "volatile sig_atomic_t" - единственный тип
// переменной, который стандарт C гарантирует безопасным для записи внутри
// обработчика сигнала (не GC_MALLOC, не обычный int с гарантией атомарности
// только "как правило") - обработчик не делает ничего, кроме этой одной
// записи, поэтому не нужен ни мьютекс, ни какая-либо другая синхронизация.
//
// Обработчик регистрируется (signal()) на КАЖДОМ вызове "запрошена_
// остановка", не один раз при старте программы - вызов "запрошена_
// остановка" внутри САМОЙ "главная" мог случиться раньше, чем компилятор
// узнал бы, что программа вообще использует эту функцию (флаг usesShutdownFlag
// в ctx выставляется как побочный эффект генерации тела "главная" - к
// моменту, когда нужно было бы решить, писать ли инициализацию В НАЧАЛЕ
// main(), тело ещё не пройдено). Вместо отдельной точки инициализации -
// сама regisration идемпотентна (signal() с тем же обработчиком - просто
// переустановка того же значения, не накопление) и достаточно дёшева для
// функции, которую по смыслу зовут в цикле поллинга (не на каждой итерации
// внутреннего горячего пути), а не тысячи раз в секунду.
//
// Никакого отдельного колбэка на остановку нет - см. package doc
// internal/builtins, "запрошена_остановка": программа сама решает, что
// делать, когда флаг взведён.
const shutdownFlagCode = `static volatile sig_atomic_t rech_shutdown_flag = 0;

static void rech_shutdown_signal_handler(int sig) {
    (void)sig;
    rech_shutdown_flag = 1;
}

static int rech_shutdown_requested(void) {
    signal(SIGINT, rech_shutdown_signal_handler);
    signal(SIGTERM, rech_shutdown_signal_handler);
    return rech_shutdown_flag != 0;
}

`
