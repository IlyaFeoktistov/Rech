// moduleOf - имя -> модуль (обратная Modules).
var moduleOf = func() map[string]string {
	m := map[string]string{}
	for mod, names := range Modules {
		for _, n := range names {
			m[n] = mod
		}
	}
	return m
}()

// ModuleOf - модуль, из которого импортируется встроенное name; ok=false -
// name не из стандартного модуля (ядро или не встроенное вовсе).
func ModuleOf(name string) (module string, ok bool) {
	module, ok = moduleOf[name]
	return module, ok
}

// Exports - даёт ли модуль module имя name.
func Exports(module, name string) bool {
	return moduleOf[name] == module && module != ""
}

// IsModule - есть ли стандартный модуль с таким именем.
func IsModule(module string) bool {
	_, ok := Modules[module]
	return ok
}

// ModuleNames - имена стандартных модулей по алфавиту.
func ModuleNames() []string {
	names := make([]string, 0, len(Modules))
	for m := range Modules {
		names = append(names, m)
	}
	sort.Strings(names)
	return names
}

// SplitPath - "стандарт/математика" -> "математика"; ok=false - путь не
// стандартного модуля.
func SplitPath(path string) (module string, ok bool) {
	if !strings.HasPrefix(path, Prefix) {
		return "", false
	}
	return strings.TrimPrefix(path, Prefix), true
}

// ImportLine - строка импорта name из его модуля
// ("использовать знак из стандарт/математика"); "" - name не из
// стандартного модуля.
func ImportLine(name string) string {
	module, ok := ModuleOf(name)
	if !ok {
		return ""
	}
	return "использовать " + name + " из " + Prefix + module
}
