// TestRunSemaphoreBoundsConcurrentTasks - "Семафор" реально ограничивает
// число ОДНОВРЕМЕННО исполняющихся "запустить"-задач: 5 задач, семафор с 2
// разрешениями - число одновременно "внутри" никогда не должно превысить 2,
// хотя все 5 запущены сразу. "текущих"/"максимум" защищены отдельной
// "Блокировкой", чтобы само измерение не гонялось (тот же приём, что и в
// mutex_test.go) - проверка семафора должна остаться верной независимо от
// того, насколько точно измерение.
func TestRunSemaphoreBoundsConcurrentTasks(t *testing.T) {
	out := runSrc(t, `
сущность Счётчики
{
    имеет:
        Целое текущих
        Целое максимум
        Блокировка блокировка

    конструктор(блокировка: Блокировка)
    {
        этот.текущих = 0
        этот.максимум = 0
        этот.блокировка = блокировка
    }

    войти()
    {
        этот.блокировка.захватить()
        этот.текущих = этот.текущих + 1
        если этот.текущих > этот.максимум
        {
            этот.максимум = этот.текущих
        }
        этот.блокировка.освободить()
    }

    выйти()
    {
        этот.блокировка.захватить()
        этот.текущих = этот.текущих - 1
        этот.блокировка.освободить()
    }
}
функция поработать(сем: Семафор, счётчики: Счётчики)
{
    сем.захватить()
    счётчики.войти()
    переменная i = 0
    пока i < 1000000
    {
        i = i + 1
    }
    счётчики.выйти()
    сем.освободить()
}
функция главная
{
    переменная сем = новый Семафор(2)
    переменная счётчики = новые Счётчики(новая Блокировка())
    переменная задача1 = запустить поработать(сем, счётчики)
    переменная задача2 = запустить поработать(сем, счётчики)
    переменная задача3 = запустить поработать(сем, счётчики)
    переменная задача4 = запустить поработать(сем, счётчики)
    переменная задача5 = запустить поработать(сем, счётчики)
    дождаться задача1
    дождаться задача2
    дождаться задача3
    дождаться задача4
    дождаться задача5
    вывести `+"`${"+`счётчики.максимум}\n`+"`"+`
}
`)
	if out != "2\n" {
		t.Fatalf("ожидалось \"2\" (семафор ограничил одновременность), получено %q", out)
	}
}

// TestRunSemaphoreSerializesWithInitialValueOne - Семафор(1) ведёт себя как
// обычная взаимоисключающая блокировка (краевой случай N=1).
func TestRunSemaphoreSerializesWithInitialValueOne(t *testing.T) {
	out := runSrc(t, `
сущность Счёт
{
    имеет:
        Целое баланс
        Семафор сем

    конструктор(баланс: Целое, сем: Семафор)
    {
        этот.баланс = баланс
        этот.сем = сем
    }

    добавить(сумма: Целое)
    {
        этот.сем.захватить()
        этот.баланс = этот.баланс + сумма
        этот.сем.освободить()
    }
}
функция пополнить(счёт: Счёт)
{
    переменная i = 0
    пока i < 2000
    {
        счёт.добавить(1)
        i = i + 1
    }
}
функция главная
{
    переменная счёт = новый Счёт(0, новый Семафор(1))
    переменная задача1 = запустить пополнить(счёт)
    переменная задача2 = запустить пополнить(счёт)
    переменная задача3 = запустить пополнить(счёт)
    дождаться задача1
    дождаться задача2
    дождаться задача3
    вывести `+"`${"+`счёт.баланс}\n`+"`"+`
}
`)
	if out != "6000\n" {
		t.Fatalf("ожидалось \"6000\" (3 задачи * 2000 - без потерь), получено %q", out)
	}
}

// TestRunSemaphoreAcquireWithTimeoutSucceedsWhenAvailable - "захватить(N)" с
// доступным разрешением ведёт себя как обычное "захватить()", просто с
// явным (не бесконечным) таймаутом - паника не должна случиться.
func TestRunSemaphoreAcquireWithTimeoutSucceedsWhenAvailable(t *testing.T) {
	out := runSrc(t, `
функция главная
{
    переменная сем = новый Семафор(1)
    сем.захватить(500)
    вывести `+"`"+`получено\n`+"`"+`
    сем.освободить()
}
`)
	if out != "получено\n" {
		t.Fatalf("получено %q, хотели \"получено\\n\"", out)
	}
}

// TestRunSemaphoreAcquireWithZeroTimeoutFailsImmediatelyWhenUnavailable -
// HTTP highload пункт 3 (admission control): "захватить(0)"
// на уже занятом семафоре не ждёт вовсе - немедленная паника (rtmsg.
// SemaphoreAcquireTimeout), а не бесконечное ожидание/зависание теста.
func TestRunSemaphoreAcquireWithZeroTimeoutFailsImmediatelyWhenUnavailable(t *testing.T) {
	err := runSrcExpectRuntimeError(t, `
функция главная
{
    переменная сем = новый Семафор(1)
    сем.захватить()
    сем.захватить(0)
}
`)
	if err == nil || !strings.Contains(err.Error(), rtmsg.SemaphoreAcquireTimeout) {
		t.Fatalf("ожидалась ошибка %q, получено: %v", rtmsg.SemaphoreAcquireTimeout, err)
	}
}

// TestRunSemaphoreAcquireWithPositiveTimeoutFailsAfterDeadline - "захватить
// (N)" на занятом семафоре, который не освобождается вовремя - паника
// ПОСЛЕ примерно N мс, не раньше и не бесконечно.
func TestRunSemaphoreAcquireWithPositiveTimeoutFailsAfterDeadline(t *testing.T) {
	err := runSrcExpectRuntimeError(t, `
функция главная
{
    переменная сем = новый Семафор(1)
    сем.захватить()
    сем.захватить(50)
}
`)
	if err == nil || !strings.Contains(err.Error(), rtmsg.SemaphoreAcquireTimeout) {
		t.Fatalf("ожидалась ошибка %q, получено: %v", rtmsg.SemaphoreAcquireTimeout, err)
	}
}
