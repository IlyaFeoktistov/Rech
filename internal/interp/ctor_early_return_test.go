package interp

import "testing"

// TestCtorBareReturnExitsBodyObjectStillCreated - "вернуть" без значения в
// конструкторе пропускает остаток тела, объект всё равно создаётся: поля,
// присвоенные до "вернуть", сохраняются, остальные - со значением по
// умолчанию. Тот же ранний выход в конструкторе базовой сущности через
// "родитель(...)" возвращает управление в конструктор наследника.
func TestCtorBareReturnExitsBodyObjectStillCreated(t *testing.T) {
	src := `сущность Точка
{
    имеет:
        Целое x
        Целое y = 9

    конструктор(x: Целое)
    {
        этот.x = x
        если x > 5 {
            вернуть
        }
        этот.y = 2
    }
}

сущность Метка наследует Точку
{
    имеет:
        Целое z

    конструктор(x: Целое)
    {
        родитель(x)
        этот.z = 3
    }
}

функция главная()
{
    Точка а = новая Точка(7)
    Точка б = новая Точка(1)
    Метка м = новая Метка(7)
    вывести(` + "`${а.x} ${а.y} ${б.x} ${б.y} ${м.y} ${м.z}\\n`" + `)
}
`
	if got, want := runSrc(t, src), "7 9 1 2 9 3\n"; got != want {
		t.Fatalf("получено %q, ожидалось %q", got, want)
	}
}
