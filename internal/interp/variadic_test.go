package interp

import "testing"

const variadicSrc = `/** Сумма любого числа слагаемых. */
публичная функция сумма(...числа: Целое): Целое
{
    переменная итог = 0
    для ч в числах {
        итог += ч
    }

    вернуть итог
}

/** Склеивает части через разделитель. */
публичная функция склеить(разделитель: Строка, ...части: Строка): Строка
{
    переменная итог = ""
    для ч в частях {
        если итог != "" {
            итог += разделитель
        }
        итог += ч
    }

    вернуть итог
}

публичная сущность Счётчик
{
    имеет:
        публичное Целое всего

    /** Прибавляет все значения. */
    публичный прибавить(...значения: Целое): Целое
    {
        для з в значениях {
            этот.всего += з
        }

        вернуть этот.всего
    }
}

публичная функция главная
{
    вывести ` + "`" + `${сумма()}\n` + "`" + `
    вывести ` + "`" + `${сумма(1, 2, 3)}\n` + "`" + `
    переменная ещё: Список<Целое> = [10, 20]
    вывести ` + "`" + `${сумма(1, ...ещё, 5, ...ещё)}\n` + "`" + `
    вывести ` + "`" + `${сумма(...ещё)}\n` + "`" + `
    вывести ` + "`" + `${склеить(", ", "а", "б", "в")}\n` + "`" + `
    переменная все = [0, ...ещё, 30]
    вывести ` + "`" + `${все.длина()} ${все.получить(3)}\n` + "`" + `
    переменная счётчик = новый Счётчик()
    вывести ` + "`" + `${счётчик.прибавить(1, 2)}\n` + "`" + `
}
`

func TestVariadicParamsAndSpread(t *testing.T) {
	got := runSrc(t, variadicSrc)
	want := "0\n6\n66\n30\nа, б, в\n4 30\n3\n"
	if got != want {
		t.Fatalf("получено %q, ожидалось %q", got, want)
	}
}

const variadicGenericIfaceSrc = `/** Первый из переданных. */
публичная функция первый<Т>(...все: Т): Т
{
    вернуть все.получить(0)
}

интерфейс Печатник
{
    напечатать(...строки: Строка)
}

публичная сущность Животное
{
    имеет:
        публичная Строка имя

    конструктор(имя: Строка)
    {
        этот.имя = имя
    }
}

публичная сущность Кошка наследует Животное
{
    конструктор(имя: Строка)
    {
        родитель(имя)
    }
}

публичная сущность Консоль реализует Печатника
{
    /** Печатает каждую строку. */
    публичный напечатать(...строки: Строка)
    {
        для строка в строках {
            вывести ` + "`" + `${строка}\n` + "`" + `
        }
    }
}

/** Имена всех животных. */
публичная функция имена(...звери: Животное): Строка
{
    переменная итог = ""
    для з в зверях {
        итог += з.имя
    }

    вернуть итог
}

/** Сумма. */
публичная функция сумма(...числа: Целое): Целое
{
    переменная итог = 0
    для ч в числах {
        итог += ч
    }

    вернуть итог
}

публичная функция главная
{
    вывести ` + "`" + `${первый(7, 8)} ${первый("а", "б")}\n` + "`" + `
    переменная п: Печатник = новая Консоль()
    п.напечатать("х", "у")
    вывести ` + "`" + `${имена(новая Кошка("Мурка"), новое Животное("Бобик"))}\n` + "`" + `
    переменная задача = запустить сумма(1, 2, 3, 4)
    вывести ` + "`" + `${дождаться задача}\n` + "`" + `
    переменная пусто: Список<Целое> = []
    вывести ` + "`" + `${сумма(...пусто)} ${первый(...[5, 6])}\n` + "`" + `
}
`

func TestVariadicGenericInterfaceUpcastAndTask(t *testing.T) {
	got := runSrc(t, variadicGenericIfaceSrc)
	want := "7 а\nх\nу\nМуркаБобик\n10\n0 5\n"
	if got != want {
		t.Fatalf("получено %q, ожидалось %q", got, want)
	}
}
