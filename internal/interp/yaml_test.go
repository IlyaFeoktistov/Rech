// TestRunYAMLParseExprMalformedTextThrowsCatchable - незакрытая двойная
// кавычка (не "текст без двоеточия вообще" - ЭТО валидный YAML, голый
// скаляр, просто несовместимый по форме с сущностью-целью, отдельная
// проверка ниже).
func TestRunYAMLParseExprMalformedTextThrowsCatchable(t *testing.T) {
	toks, err := lexer.New(`
сущность Конфиг
{
    имеет:
        порт: Целое
}
функция главная
{
    попытаться {
        переменная конфиг = разобрать YAML "порт: \"неоконченная строка" как Конфиг
    } поймать(ошибка: ОшибкаРазбора) {
        вывести ` + "`${" + `ошибка.сообщение}\n` + "`" + `
    }
}
`).Tokenize()
	if err != nil {
		t.Fatalf("лексер: %v", err)
	}
	prog, err := parser.New(toks).ParseProgram()
	if err != nil {
		t.Fatalf("парсер: %v", err)
	}
	irProg, err := semantic.Analyze(prog)
	if err != nil {
		t.Fatalf("семантический анализ: %v", err)
	}
	var buf bytes.Buffer
	if err := Run(irProg, &buf, strings.NewReader("")); err != nil {
		t.Fatalf("исполнение: %v", err)
	}
	want := "разобрать YAML: текст не является корректным YAML\n"
	if buf.String() != want {
		t.Fatalf("получили %q, хотели %q", buf.String(), want)
	}
}
