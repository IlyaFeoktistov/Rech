// TestRunYAMLParseExprTopLevelScalar - НАЙДЕННЫЙ И ИСПРАВЛЕННЫЙ баг:
// парсер раньше всегда пробовал разобрать документ как отображение/
// последовательность (rech_yaml_parse_node), даже когда весь документ -
// голый скаляр без единого ":"/"- " (например, "разобрать YAML \"42\" как
// Целое") - "42" не похоже на ключ отображения, но старый код всё равно
// уходил в rech_yaml_parse_map, который не находил ни одного ":" и падал
// с ошибкой разбора. rech_yaml_line_looks_like_key (cbackend)/
// lineLooksLikeYAMLKey (interp) отличают "весь документ - скаляр" от
// "документ - отображение".
func TestRunYAMLParseExprTopLevelScalar(t *testing.T) {
	got := runSrc(t, `
функция главная
{
    переменная число = разобрать YAML "42" как Целое
    вывести `+"`${"+`число}\n`+"`"+`

    переменная строка = разобрать YAML "\"привет\"" как Строка
    вывести `+"`${"+`строка}\n`+"`"+`

    переменная логическое = разобрать YAML "true" как Логическое
    вывести `+"`${"+`логическое}\n`+"`"+`
}
`)
	want := "42\nпривет\nистина\n"
	if got != want {
		t.Fatalf("получили %q, хотели %q", got, want)
	}
}

