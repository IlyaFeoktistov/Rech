func TestRunYAMLSerializeExprRoundTrip(t *testing.T) {
	got := runSrc(t, `
сущность База
{
    имеет:
        путь: Строка
}
сущность Конфиг
{
    имеет:
        порт: Целое
        имя: Строка
        база: База
        источники: Список<Строка>
}
функция главная
{
    переменная бд = новая База()
    бд.путь = "/tmp/x"

    переменная конфиг = новый Конфиг()
    конфиг.порт = 9090
    конфиг.имя = "тест"
    конфиг.база = бд
    конфиг.источники = новый Список<Строка>()
    конфиг.источники.добавить("a")
    конфиг.источники.добавить("b")

    переменная текст = сериализовать YAML конфиг
    вывести `+"`${"+`текст}\n`+"`"+`

    переменная обратно = разобрать YAML текст как Конфиг
    вывести `+"`${"+`обратно.порт}\n`+"`"+`
    вывести `+"`${"+`обратно.имя}\n`+"`"+`
    вывести `+"`${"+`обратно.база.путь}\n`+"`"+`
    вывести `+"`${"+`обратно.источники.длина()}\n`+"`"+`
    вывести `+"`${"+`обратно.источники.получить(0)}\n`+"`"+`
    вывести `+"`${"+`обратно.источники.получить(1)}\n`+"`"+`
}
`)
	want := "порт: 9090\n" +
		"имя: \"тест\"\n" +
		"база:\n" +
		"  путь: \"/tmp/x\"\n" +
		"источники:\n" +
		"  - \"a\"\n" +
		"  - \"b\"\n" +
		"\n9090\nтест\n/tmp/x\n2\na\nb\n"
	if got != want {
		t.Fatalf("получили %q, хотели %q", got, want)
	}
}

