package interp

import "testing"

// TestOperatorOverloadExecutes - перегруженный оператор реально исполняется
// как обычный статический метод (см. internal/semantic/operator.go -
// перегрузка резолвится ЦЕЛИКОМ в semantic, interp просто исполняет
// ir.StaticMethodCallExpr под синтетическим именем, ничего специального
// про операторы не знает).
func TestOperatorOverloadExecutes(t *testing.T) {
	out := runSrc(t, `
структура Вектор
{
    имеет:
        x: Действительное
        y: Действительное

    статический публичный оператор +(a: Вектор, b: Вектор): Вектор
    {
        вернуть новый Вектор(a.x + b.x, a.y + b.y)
    }

    статический публичный оператор -(a: Вектор, b: Вектор): Вектор
    {
        вернуть новый Вектор(a.x - b.x, a.y - b.y)
    }

    статический публичный оператор ==(a: Вектор, b: Вектор): Логическое
    {
        вернуть a.x == b.x и a.y == b.y
    }
}

функция главная
{
    переменная a = новый Вектор(1.0, 2.0)
    переменная b = новый Вектор(3.0, 4.0)
    переменная c = a + b
    вывести `+"`${"+`"c.x=" + (Строка) c.x + " c.y=" + (Строка) c.y}\n`+"`"+`

    переменная d = a - b
    вывести `+"`${"+`"d.x=" + (Строка) d.x + " d.y=" + (Строка) d.y}\n`+"`"+`

    если a == a {
        вывести `+"`"+`a равен a\n`+"`"+`
    }
    если не (a == b) {
        вывести `+"`"+`a не равен b\n`+"`"+`
    }
}
`)
	want := "c.x=4 c.y=6\nd.x=-2 d.y=-2\na равен a\na не равен b\n"
	if out != want {
		t.Fatalf("ожидался вывод %q, получено %q", want, out)
	}
}
