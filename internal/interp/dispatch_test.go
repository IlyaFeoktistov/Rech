package interp

import "testing"

func TestRunOverriddenMethodDispatchesToConcreteTypeThroughBaseTypedParam(t *testing.T) {
	got := runSrc(t, `
сущность Животное
{
    издать_звук(): Строка
    {
        вернуть "..."
    }
}
сущность Кошка наследует Животное
{
    издать_звук(): Строка
    {
        вернуть "мяу"
    }
}
функция озвучить(а: Животное): Строка
{
    вернуть а.издать_звук()
}
функция главная
{
    переменная кот = новая Кошка()
    вывести озвучить(кот)
}
`)
	if got != "мяу\n" {
		t.Fatalf("ожидался вызов переопределённого метода через параметр базового типа, получили %q", got)
	}
}

func TestRunInheritedUnmodifiedMethodCallableOnDerivedInstance(t *testing.T) {
	got := runSrc(t, `
сущность Животное
{
    имеет:
        имя: Строка

    представиться(): Строка
    {
        вернуть этот.имя
    }
}
сущность Собака наследует Животное
{
    имеет:
        порода: Строка
}
функция главная
{
    переменная пёс = новая Собака("Шарик", "дворняга")
    вывести пёс.представиться()
    вывести пёс.порода
}
`)
	if got != "Шарик\nдворняга\n" {
		t.Fatalf("ожидался унаследованный неизменённый метод + собственное поле, получили %q", got)
	}
}

func TestRunInterfaceTypedParamDispatchesToConcreteImplementation(t *testing.T) {
	got := runSrc(t, `
интерфейс Звучащий
{
    издать_звук(): Строка
}
сущность Кошка реализует Звучащий
{
    издать_звук(): Строка
    {
        вернуть "мяу"
    }
}
сущность Собака реализует Звучащий
{
    издать_звук(): Строка
    {
        вернуть "гав"
    }
}
функция озвучить(х: Звучащий): Строка
{
    вернуть х.издать_звук()
}
функция главная
{
    переменная кот = новая Кошка()
    переменная собака = новая Собака()
    вывести озвучить(кот)
    вывести озвучить(собака)
}
`)
	if got != "мяу\nгав\n" {
		t.Fatalf("ожидалась диспетчеризация по конкретному типу через интерфейсный параметр, получили %q", got)
	}
}

func TestRunMultiLevelInheritanceOverrideChain(t *testing.T) {
	got := runSrc(t, `
сущность А
{
    имя(): Строка
    {
        вернуть "А"
    }
}
сущность Б наследует А
{
}
сущность В наследует Б
{
    имя(): Строка
    {
        вернуть "В"
    }
}
функция назвать(х: А): Строка
{
    вернуть х.имя()
}
функция главная
{
    переменная б = новый Б()
    переменная объект_в = новый В()
    вывести назвать(б)
    вывести назвать(объект_в)
}
`)
	if got != "А\nВ\n" {
		t.Fatalf("ожидалась цепочка наследования в 3 уровня с переопределением на последнем, получили %q", got)
	}
}
