func TestRunParseDateRoundTrip(t *testing.T) {
	got := runSrc(t, `
функция главная
{
    переменная д = разобрать_дату("2023-11-14 22:13:20")
    если д != Ничто {
        переменная дд = д ?? время_как_дата(0)
        вывести дату_в_строку(дд)
    }
    переменная плохая = разобрать_дату("не дата")
    вывести плохая == Ничто
}
`)
	want := "2023-11-14 22:13:20\nистина\n"
	if got != want {
		t.Fatalf("получили %q, хотели %q", got, want)
	}
}

