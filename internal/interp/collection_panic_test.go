package interp

import "testing"

// Выход за границы/пустая коллекция - Паника, которую ловит
// "поймать(о: Паника)", с тем же текстом, что и в cbackend.
func TestCollectionOutOfRangeIsCatchablePanic(t *testing.T) {
	const want = "получить: индекс вне границ у Список<Целое>\nустановить: индекс вне границ у Список<Целое>\nудалить: индекс вне границ у Список<Целое>\nпервый: индекс вне границ у Список<Целое>\nпоследний: индекс вне границ у Список<Целое>\n&сп[i]: индекс вне границ у Список<Целое>\nсловарь.получить: ключ не найден в Словарь<Строка, Целое>\nсловарь.удалить: без паники\nснять: нельзя снять/получить верх пустой Стопка<Целое>\nверх: нельзя снять/получить верх пустой Стопка<Целое>\nизвлечь: нельзя извлечь/получить первый элемент пустой Очередь<Целое>\n"
	if got := runSrc(t, `функция проверить(имя: Строка, действие: Вызываемый())
{
    попытаться {
        действие()
        вывести `+"`"+`${имя}: без паники\n`+"`"+`
    } поймать(о: Паника) {
        вывести `+"`"+`${имя}: ${о}\n`+"`"+`
    }
}

функция главная
{
    Список<Целое> сп = []
    Словарь<Строка, Целое> сл = новый Словарь<Строка, Целое>()
    Стопка<Целое> ст = новая Стопка<Целое>()
    Очередь<Целое> оч = новая Очередь<Целое>()
    проверить("получить", функция () { вывести `+"`"+`${сп.получить(1)}`+"`"+` })
    проверить("установить", функция () { сп.установить(1, 2) })
    проверить("удалить", функция () { вывести `+"`"+`${сп.удалить(0)}`+"`"+` })
    проверить("первый", функция () { вывести `+"`"+`${сп.первый()}`+"`"+` })
    проверить("последний", функция () { вывести `+"`"+`${сп.последний()}`+"`"+` })
    проверить("&сп[i]", функция () { *Целое п = &сп[3] })
    проверить("словарь.получить", функция () { вывести `+"`"+`${сл.получить("нет")}`+"`"+` })
    проверить("словарь.удалить", функция () { сл.удалить("нет") })
    проверить("снять", функция () { вывести `+"`"+`${ст.снять()}`+"`"+` })
    проверить("верх", функция () { вывести `+"`"+`${ст.верх()}`+"`"+` })
    проверить("извлечь", функция () { вывести `+"`"+`${оч.извлечь()}`+"`"+` })
}
`); got != want {
		t.Fatalf("хотели:\n%q\nполучили:\n%q", want, got)
	}
}
