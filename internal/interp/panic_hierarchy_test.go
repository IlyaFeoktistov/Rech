package interp

import "testing"

// Встроенные паники ловятся по конкретному типу и по "Паника"; своя паника
// ("наследует Паника") не ловится "поймать(Исключение)" - тот же вывод,
// что у cbackend.
func TestPanicHierarchyCatchBySpecificType(t *testing.T) {
	const want = "ДелениеНаНоль: деление на ноль\nВыходЗаГраницы: индекс вне границ у Список<Целое>\nПустаяКоллекция: нельзя снять/получить верх пустой Стопка<Целое>\nКлючНеНайден: ключ не найден в Словарь<Строка, Целое>\nНеверноеПриведение: каст (Значение -> Строка): фактический тип значения - Целое\nНарушениеУтверждения: утверждение не выполнено (строка 42): ноль не один\nПаника: нет порта\nсвоя паника: своя\nсмешанный: индекс вне границ у Список<Целое>\nокончательно\n"
	if got := runSrc(t, `сущность ОшибкаКонфигурации наследует Паника
{
    конструктор(сообщение: Строка)
    {
        родитель(сообщение)
    }
}

функция тип_паники(действие: Вызываемый()): Строка
{
    попытаться {
        действие()
    } поймать(о: ДелениеНаНоль) {
        вернуть `+"`"+`ДелениеНаНоль: ${о}`+"`"+`
    } поймать(о: ВыходЗаГраницы) {
        вернуть `+"`"+`ВыходЗаГраницы: ${о.сообщение}`+"`"+`
    } поймать(о: ПустаяКоллекция | КлючНеНайден) {
        Строка вид = о относится к ПустаяКоллекция ? "ПустаяКоллекция" : "КлючНеНайден"
        вернуть `+"`"+`${вид}: ${о}`+"`"+`
    } поймать(о: НеверноеПриведение) {
        вернуть `+"`"+`НеверноеПриведение: ${о}`+"`"+`
    } поймать(о: НарушениеУтверждения) {
        вернуть `+"`"+`НарушениеУтверждения: ${о}`+"`"+`
    } поймать(о: Паника) {
        вернуть `+"`"+`Паника: ${о}`+"`"+`
    }
    вернуть "без паники"
}

функция главная
{
    Целое ноль = 0
    Список<Целое> сп = []
    Словарь<Строка, Целое> сл = новый Словарь<Строка, Целое>()
    Стопка<Целое> ст = новая Стопка<Целое>()
    Значение з = (Значение) 5
    вывести `+"`"+`${тип_паники(функция () { вывести `+"`"+`${7 / ноль}`+"`"+` })}\n`+"`"+`
    вывести `+"`"+`${тип_паники(функция () { вывести `+"`"+`${сп.получить(3)}`+"`"+` })}\n`+"`"+`
    вывести `+"`"+`${тип_паники(функция () { вывести `+"`"+`${ст.снять()}`+"`"+` })}\n`+"`"+`
    вывести `+"`"+`${тип_паники(функция () { вывести `+"`"+`${сл.получить("к")}`+"`"+` })}\n`+"`"+`
    вывести `+"`"+`${тип_паники(функция () { вывести `+"`"+`${з как Строка}`+"`"+` })}\n`+"`"+`
    вывести `+"`"+`${тип_паники(функция () { утверждать ноль == 1, "ноль не один" })}\n`+"`"+`
    вывести `+"`"+`${тип_паники(функция () { выбросить новая ОшибкаКонфигурации("нет порта") })}\n`+"`"+`

    попытаться {
        выбросить новая ОшибкаКонфигурации("своя")
    } поймать(о: Исключение) {
        вывести `+"`"+`не должно поймать\n`+"`"+`
    } поймать(о: ОшибкаКонфигурации) {
        вывести `+"`"+`своя паника: ${о}\n`+"`"+`
    }

    попытаться {
        вывести `+"`"+`${сп.получить(0)}`+"`"+`
    } поймать(о: Паника | Исключение) {
        вывести `+"`"+`смешанный: ${о}\n`+"`"+`
    } окончательно {
        вывести `+"`"+`окончательно\n`+"`"+`
    }
}
`); got != want {
		t.Fatalf("хотели:\n%q\nполучили:\n%q", want, got)
	}
}
