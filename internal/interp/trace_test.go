package interp

import "testing"

// TestRunPanicIncludesCallChain - паника рантайма (деление на ноль) внутри
// цепочки вложенных вызовов - err.Error() несёт стек вызовов от места
// паники до "главная" (см. package doc internal/interp/trace.go), тот же
// формат, что и cbackend (rtmsg.TraceHeader/TraceFrameFormat).
func TestRunPanicIncludesCallChain(t *testing.T) {
	err := runSrcExpectRuntimeError(t, `
функция внутренняя(число: Целое): Целое
{
    вернуть 10 / число
}

функция средняя(число: Целое): Целое
{
    переменная результат = внутренняя(число)
    вернуть результат
}

функция главная
{
    переменная х = средняя(0)
    вывести х
}
`)
	if err == nil {
		t.Fatalf("ожидалась ошибка - деление на ноль")
	}
	want := "выполнение прервано: деление на ноль\nстек вызовов:\n  в внутренняя, строка 4\n  в средняя, строка 9\n  в главная, строка 15"
	if got := err.Error(); got != want {
		t.Fatalf("неожиданный текст ошибки:\nполучено: %q\nожидалось: %q", got, want)
	}
}

// TestRunPanicIncludesMethodFrame - метод показывается как "Тип.метод" в
// стеке вызовов.
func TestRunPanicIncludesMethodFrame(t *testing.T) {
	err := runSrcExpectRuntimeError(t, `
сущность Счёт
{
    имеет:
        баланс: Целое

    конструктор(баланс: Целое)
    {
        этот.баланс = баланс
    }

    снять(сумма: Целое): Целое
    {
        переменная новый_баланс = этот.баланс / сумма
        вернуть новый_баланс
    }
}

функция главная
{
    переменная счёт = новый Счёт(100)
    вывести счёт.снять(0)
}
`)
	if err == nil {
		t.Fatalf("ожидалась ошибка - деление на ноль")
	}
	want := "выполнение прервано: деление на ноль\nстек вызовов:\n  в Счёт.снять, строка 14\n  в главная, строка 22"
	if got := err.Error(); got != want {
		t.Fatalf("неожиданный текст ошибки:\nполучено: %q\nожидалось: %q", got, want)
	}
}

// TestRunTryStmtRestoresTraceAfterCatch - после того как "поймать" перехватило
// исключение, следующая (уже НЕ пойманная) паника не несёт в стеке кадры
// уже завершившегося, пойманного вызова - тот же принцип, что и у
// cbackend.generateIRTryStmt (traceVar, восстановление rech_trace_top).
func TestRunTryStmtRestoresTraceAfterCatch(t *testing.T) {
	err := runSrcExpectRuntimeError(t, `
функция глубоко(число: Целое)
{
    попытаться
    {
        выбросить новое Исключение("первая")
    }
    поймать(иск: Исключение)
    {
        вывести "поймано"
    }
    выбросить новое Исключение("вторая")
}

функция главная
{
    глубоко(1)
}
`)
	if err == nil {
		t.Fatalf("ожидалась ошибка - необработанное исключение")
	}
	want := "выполнение прервано: необработанное исключение Исключение: вторая\nстек вызовов:\n  в глубоко, строка 12\n  в главная, строка 17"
	if got := err.Error(); got != want {
		t.Fatalf("неожиданный текст ошибки:\nполучено: %q\nожидалось: %q", got, want)
	}
}
