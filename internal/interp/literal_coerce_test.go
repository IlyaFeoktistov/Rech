package interp

import "testing"

// Числовая константа приводится к объявленному типу - тот же вывод, что и
// у cbackend.
func TestNumericConstCoercedToDeclaredType(t *testing.T) {
	const want = "5 6 255 -600 1.5 -128 истина 1048576\n"
	if got := runSrc(t, `функция главная
{
    Целое8 а = 0
    а = 5
    Целое8 г = а + 1
    Байт б = 255
    Целое16 ц = -300 * 2
    Дробное д = 1.5
    ?Целое8 м = -128
    Логическое л = г > 3
    Целое32 сд = 1 << 20
    вывести `+"`"+`${а} ${г} ${б} ${ц} ${д} ${м ?? 0} ${л} ${сд}\n`+"`"+`
}
`); got != want {
		t.Fatalf("хотели %q, получили %q", want, got)
	}
}
