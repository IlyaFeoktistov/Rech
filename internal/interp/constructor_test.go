package interp

import "testing"

func TestRunExplicitConstructorAssignsFields(t *testing.T) {
	got := runSrc(t, `
сущность Точка
{
    имеет:
        x: Целое
        y: Целое

    конструктор(x: Целое, y: Целое)
    {
        этот.x = x
        этот.y = y
    }
}
функция главная
{
    переменная точка = новая Точка(3, 4)
    вывести точка.x
    вывести точка.y
}
`)
	if got != "3\n4\n" {
		t.Fatalf("ожидались поля, присвоенные явным конструктором, получили %q", got)
	}
}

// TestRunExplicitConstructorFieldNotSetStaysZero - поле, которое тело
// конструктора не присвоило явно, остаётся нулевым значением своего типа
// (та же гарантия, что и GC_MALLOC в cbackend) - не паникует и не падает с
// ошибкой отсутствующего ключа.
func TestRunExplicitConstructorFieldNotSetStaysZero(t *testing.T) {
	got := runSrc(t, `
сущность Счётчик
{
    имеет:
        значение: Целое
        метка: Строка

    конструктор(метка: Строка)
    {
        этот.метка = метка
    }
}
функция главная
{
    переменная счётчик = новый Счётчик("а")
    вывести счётчик.значение
    вывести счётчик.метка
}
`)
	if got != "0\nа\n" {
		t.Fatalf("ожидалось нулевое значение непроинициализированного поля, получили %q", got)
	}
}

func TestRunParentCallStmtRunsBaseConstructorOnSameObject(t *testing.T) {
	got := runSrc(t, `
сущность Пользователь
{
    имеет:
        имя: Строка
        возраст: Целое

    конструктор(имя: Строка)
    {
        этот.имя = имя
        этот.возраст = 0
    }
}
сущность Сотрудник наследует Пользователя
{
    имеет:
        зарплата: Целое

    конструктор(имя: Строка, зарплата: Целое)
    {
        родитель(имя)
        этот.зарплата = зарплата
    }
}
функция главная
{
    переменная сотрудник = новый Сотрудник("Аня", 1000)
    вывести сотрудник.имя
    вывести сотрудник.возраст
    вывести сотрудник.зарплата
}
`)
	if got != "Аня\n0\n1000\n" {
		t.Fatalf("ожидалось, что \"родитель(...)\" исполнит тело базового конструктора на том же объекте, получили %q", got)
	}
}

// TestRunEntityWithoutOwnConstructorKeepsImplicitForm - у наследника без
// СВОЕГО "конструктор" - "новый" остаётся неявным позиционным
// присваиванием всех полей (включая унаследованные), даже если у базовой
// сущности есть явный конструктор - см. package doc entitySig.HasCtor.
// TestRunImplicitConstructorOmitsTrailingDefaultField - без явного
// "конструктор" поле со значением по умолчанию ("имеет: y: Целое = 0")
// можно пропустить в позиционном "новый Тип(...)" - тем самым оно
// становится последним, необязательным.
func TestRunImplicitConstructorOmitsTrailingDefaultField(t *testing.T) {
	got := runSrc(t, `
сущность Точка
{
    имеет:
        x: Целое
        y: Целое = 9
}
функция главная
{
    переменная а = новая Точка(1)
    переменная б = новая Точка(1, 2)
    вывести а.x
    вывести а.y
    вывести б.x
    вывести б.y
}
`)
	if got != "1\n9\n1\n2\n" {
		t.Fatalf("ожидалось значение по умолчанию для пропущенного поля, получили %q", got)
	}
}

// TestRunImplicitConstructorNamedFormOmitsDefaultField - та же гарантия, но
// в именованной форме "новый Тип(поле: значение)".
func TestRunImplicitConstructorNamedFormOmitsDefaultField(t *testing.T) {
	got := runSrc(t, `
сущность Пользователь
{
    имеет:
        имя: Строка
        роль: Строка = "гость"
}
функция главная
{
    переменная п = новый Пользователь(имя: "Аня")
    вывести п.имя
    вывести п.роль
}
`)
	if got != "Аня\nгость\n" {
		t.Fatalf("ожидалось значение по умолчанию для поля роль, получили %q", got)
	}
}

// TestRunExplicitConstructorFieldStartsAtDefaultBeforeBody - у сущности с
// явным конструктором поле со значением по умолчанию начинает с него, ещё
// до тела конструктора, а не с нулевого значения - тело может
// переопределить его явным присваиванием.
func TestRunExplicitConstructorFieldStartsAtDefaultBeforeBody(t *testing.T) {
	got := runSrc(t, `
сущность Счётчик
{
    имеет:
        шаг: Целое = 1
        значение: Целое = 100

    конструктор(значение: Целое)
    {
        этот.значение = значение
    }
}
функция главная
{
    переменная сч = новый Счётчик(5)
    вывести сч.шаг
    вывести сч.значение
}
`)
	if got != "1\n5\n" {
		t.Fatalf("ожидался дефолт для поля шаг и переопределённое конструктором значение, получили %q", got)
	}
}

