package interp

import "testing"

const typestateTestEntities = `
сущность Пользователь
{
    состояние: авторизован

    имеет:
        имя: Строка

    конструктор(имя: Строка)
    {
        этот.имя = имя
    }

    авторизовать()
    {
        этот становится авторизованным
    }

    представиться(п: АвторизованныйПользователь): Строка
    {
        вернуть п.имя
    }
}
функция авторизовать_кого_то(п: Пользователь)
{
    п.авторизовать()
}
`

// TestRunStateCheckPassesWhenActuallyEstablishedAtRuntime - established не
// смог доказать переход (эффект чужой функции), но объект РЕАЛЬНО прошёл
// его - рантайм-проверка (ir.StateCheckExpr) пропускает значение дальше
// без исключения.
func TestRunStateCheckPassesWhenActuallyEstablishedAtRuntime(t *testing.T) {
	got := runSrc(t, typestateTestEntities+`
функция главная
{
    переменная п = новый Пользователь("Аня")
    авторизовать_кого_то(п)
    вывести `+"`${"+`п.представиться(п)}\n`+"`"+`
}
`)
	if got != "Аня\n" {
		t.Fatalf("ожидалось \"Аня\", получено %q", got)
	}
}

// TestRunHasStateExprReflectsRuntimeState - "относится к
// <ПроизводныйТипСостояния>" сообщает ТЕКУЩЕЕ (времени исполнения)
// состояние, никогда не бросает - в отличие от рантайм-проверки,
// вставляемой компилятором автоматически (StateCheckExpr).
func TestRunHasStateExprReflectsRuntimeState(t *testing.T) {
	got := runSrc(t, typestateTestEntities+`
функция главная
{
    переменная аня = новый Пользователь("Аня")
    переменная оля = новый Пользователь("Оля")
    аня.авторизовать()

    если аня относится к АвторизованныйПользователь
    {
        вывести `+"`"+`аня да\n`+"`"+`
    }
    если оля относится к АвторизованныйПользователь
    {
        вывести `+"`"+`оля да\n`+"`"+`
    }
    иначе
    {
        вывести `+"`"+`оля нет\n`+"`"+`
    }
}
`)
	if got != "аня да\nоля нет\n" {
		t.Fatalf("ожидалось \"аня да\\nоля нет\\n\", получено %q", got)
	}
}

// TestRunOppositeMethodClearsRuntimeStateFlag - метод, объявленный
// "противоположностью" другому, реально снимает бит рантайм-хранилища при
// вызове, даже без собственного "становится" в теле (ir.MethodCallExpr.
// RevokesStates) - иначе "относится к" (HasStateExpr) после такого вызова
// ошибочно считал бы состояние по-прежнему установленным.
func TestRunOppositeMethodClearsRuntimeStateFlag(t *testing.T) {
	got := runSrc(t, `
сущность Пользователь
{
    состояние: вошедший

    имеет:
        имя: Строка

    конструктор(имя: Строка)
    {
        этот.имя = имя
    }

    войти(): Пользователь
    {
        этот становится вошедшим
        вернуть этот
    }

    выйти() `+"`противоположность:войти`"+`
    {
    }
}
функция главная
{
    переменная аня = новый Пользователь("Аня")
    аня = аня.войти()
    аня.выйти()

    если аня относится к ВошедшийПользователь
    {
        вывести `+"`"+`БАГ\n`+"`"+`
    }
    иначе
    {
        вывести `+"`"+`ок\n`+"`"+`
    }
}
`)
	if got != "ок\n" {
		t.Fatalf("ожидалось \"ок\\n\" (бит реально снят), получено %q", got)
	}
}

// TestRunOpaqueCallInvalidatesEstablishedSoStateCheckCatchesRevoke -
// сущность, переданная простым именем в обычный (не получателя метода)
// параметр опаque-функции, теряет established целиком после вызова
// (internal/semantic, invalidateEstablishedForOpaqueArg) - здесь опаque-
// функция внутри реально снимает состояние через метод-противоположность;
// без инвалидации established последующий вызов не получил бы рантайм-
// проверку вообще и прошёл бы молча неверно.
func TestRunOpaqueCallInvalidatesEstablishedSoStateCheckCatchesRevoke(t *testing.T) {
	got := runSrc(t, `
сущность Пользователь
{
    состояние: вошедший

    имеет:
        имя: Строка

    конструктор(имя: Строка)
    {
        этот.имя = имя
    }

    войти(): Пользователь
    {
        этот становится вошедшим
        вернуть этот
    }

    выйти() `+"`противоположность:войти`"+`
    {
    }

    представиться(п: ВошедшийПользователь): Строка
    {
        вернуть п.имя
    }
}
функция обернуть_выход(п: Пользователь)
{
    п.выйти()
}
функция главная
{
    переменная аня = новый Пользователь("Аня")
    аня = аня.войти()
    обернуть_выход(аня)
    попытаться
    {
        вывести `+"`${"+`аня.представиться(аня)}\n`+"`"+`
        вывести `+"`"+`БАГ: рантайм-проверка не сработала\n`+"`"+`
    }
    поймать (иск: Исключение)
    {
        вывести `+"`${"+`"ок: " + иск.сообщение}\n`+"`"+`
    }
}
`)
	want := "ок: объект типа \"Пользователь\" не находится в требуемом состоянии \"вошедший\"\n"
	if got != want {
		t.Fatalf("ожидалось %q, получено %q", want, got)
	}
}

