package interp

import "testing"

// TestRunMutexSerializesConcurrentFieldUpdates - "Блокировка" реально
// защищает поле общей сущности между несколькими "запустить"-задачами:
// без синхронизации итоговое значение было бы недетерминированным
// (потерянные обновления), с ней - всегда точным.
func TestRunMutexSerializesConcurrentFieldUpdates(t *testing.T) {
	out := runSrc(t, `
сущность Счёт
{
    имеет:
        Целое баланс
        Блокировка блокировка

    конструктор(баланс: Целое, блокировка: Блокировка)
    {
        этот.баланс = баланс
        этот.блокировка = блокировка
    }

    добавить(сумма: Целое)
    {
        этот.блокировка.захватить()
        этот.баланс = этот.баланс + сумма
        этот.блокировка.освободить()
    }
}
функция пополнить(счёт: Счёт)
{
    переменная i = 0
    пока i < 2000
    {
        счёт.добавить(1)
        i = i + 1
    }
}
функция главная
{
    переменная счёт = новый Счёт(0, новая Блокировка())
    переменная задача1 = запустить пополнить(счёт)
    переменная задача2 = запустить пополнить(счёт)
    переменная задача3 = запустить пополнить(счёт)
    дождаться задача1
    дождаться задача2
    дождаться задача3
    вывести `+"`${"+`счёт.баланс}\n`+"`"+`
}
`)
	if out != "6000\n" {
		t.Fatalf("ожидалось \"6000\" (3 задачи * 2000 - под блокировкой без потерь), получено %q", out)
	}
}

// TestRunConcurrentFieldAccessOnSharedEntityDoesNotCrashInterpreter -
// регрессионный тест: конкурентный доступ к РАЗНЫМ полям одного объекта
// (одна задача пишет "баланс", другая тем же тактом читает "блокировка",
// чтобы её захватить) раньше ронял процесс целиком ("fatal error:
// concurrent map read and map write" - свойство встроенной map в Go, не
// поведение отдельных полей C-структуры) - см. entityObj.fieldsMu,
// interp.go. Сам факт, что тест завершается без паники/fatal error - и
// есть проверка (значение баланса при этом всё равно детерминировано,
// потому что запись защищена "Блокировкой").
func TestRunConcurrentFieldAccessOnSharedEntityDoesNotCrashInterpreter(t *testing.T) {
	out := runSrc(t, `
сущность Счёт
{
    имеет:
        Целое баланс
        Блокировка блокировка

    конструктор(баланс: Целое, блокировка: Блокировка)
    {
        этот.баланс = баланс
        этот.блокировка = блокировка
    }

    списать(сумма: Целое)
    {
        этот.блокировка.захватить()
        этот.баланс = этот.баланс - сумма
        этот.блокировка.освободить()
    }
}
функция обработать(счёт: Счёт)
{
    переменная i = 0
    пока i < 2000
    {
        счёт.списать(1)
        i = i + 1
    }
}
функция главная
{
    переменная счёт = новый Счёт(4000, новая Блокировка())
    переменная задача1 = запустить обработать(счёт)
    переменная задача2 = запустить обработать(счёт)
    дождаться задача1
    дождаться задача2
    вывести `+"`${"+`счёт.баланс}\n`+"`"+`
}
`)
	if out != "0\n" {
		t.Fatalf("ожидалось \"0\", получено %q", out)
	}
}
