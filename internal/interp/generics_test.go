package interp

import "testing"

func TestRunGenericEntityAndFunction(t *testing.T) {
	out := runSrc(t, `
сущность Коробка<T>
{
    имеет:
        T содержимое

    конструктор(содержимое: T)
    {
        этот.содержимое = содержимое
    }

    получить(): T
    {
        вернуть этот.содержимое
    }
}
функция первый<T>(список: Список<T>): T
{
    вернуть список.получить(0)
}
функция главная
{
    переменная коробка = новая Коробка<Целое>(5)
    вывести `+"`${"+`коробка.получить()}\n`+"`"+`

    переменная сп = новый Список<Строка>()
    сп.добавить("привет")
    переменная результат = первый<Строка>(сп)
    вывести `+"`${"+`результат}\n`+"`"+`
}
`)
	if out != "5\nпривет\n" {
		t.Fatalf("ожидалось \"5\\nпривет\\n\", получено %q", out)
	}
}

func TestRunGenericMultipleParamsAndNesting(t *testing.T) {
	out := runSrc(t, `
сущность Пара<A, Б>
{
    имеет:
        A первый
        Б второй

    конструктор(первый: A, второй: Б)
    {
        этот.первый = первый
        этот.второй = второй
    }
}
функция главная
{
    переменная внутрь = новая Пара<Целое, Целое>(1, 2)
    переменная снаружи = новая Пара<Целое, Пара<Целое, Целое>>(0, внутрь)
    вывести `+"`${"+`снаружи.второй.первый}\n`+"`"+`
    вывести `+"`${"+`снаружи.второй.второй}\n`+"`"+`
}
`)
	if out != "1\n2\n" {
		t.Fatalf("ожидалось \"1\\n2\\n\", получено %q", out)
	}
}

func TestRunGenericInterfaceConstraintDispatchesPolymorphically(t *testing.T) {
	out := runSrc(t, `
интерфейс Звучащий
{
    издать_звук(): Строка
}
сущность Кошка реализует Звучащий
{
    издать_звук(): Строка
    {
        вернуть "мяу"
    }
}
сущность Собака реализует Звучащий
{
    издать_звук(): Строка
    {
        вернуть "гав"
    }
}
функция крикнуть<T как Звучащий>(x: T): Строка
{
    вернуть x.издать_звук()
}
функция главная
{
    переменная кот = новая Кошка()
    переменная пёс = новая Собака()
    переменная звукКота = крикнуть<Кошка>(кот)
    вывести `+"`${"+`звукКота}\n`+"`"+`
    переменная звукПса = крикнуть<Собака>(пёс)
    вывести `+"`${"+`звукПса}\n`+"`"+`
}
`)
	if out != "мяу\nгав\n" {
		t.Fatalf("ожидалось \"мяу\\nгав\\n\", получено %q", out)
	}
}
