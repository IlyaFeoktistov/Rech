func TestRunXMLRoundTripEntityListPrimitives(t *testing.T) {
	got := runSrc(t, `
сущность Адрес
{
    имеет:
        город: Строка
}
сущность Пользователь
{
    имеет:
        имя: Строка
        возраст: Целое
        активен: Логическое
        адрес: Адрес
        теги: Список<Строка>
}
функция главная
{
    переменная адрес = новый Адрес("Москва")
    переменная теги = новый Список<Строка>()
    теги.добавить("а")
    теги.добавить("б & в")
    переменная п = новый Пользователь("Аня <А>", 30, истина, адрес, теги)
    переменная текст = сериализовать XML п
    вывести текст

    переменная восстановленный = разобрать XML текст как Пользователь
    вывести восстановленный.имя
    вывести восстановленный.возраст
    вывести восстановленный.активен
    вывести восстановленный.адрес.город
    вывести восстановленный.теги.длина()
    вывести восстановленный.теги.получить(1)

    переменная числа = новый Список<Целое>()
    числа.добавить(1)
    числа.добавить(2)
    числа.добавить(3)
    переменная числаТекст = сериализовать XML числа
    переменная числаНазад = разобрать XML числаТекст как Список<Целое>
    вывести числаНазад.длина()
    вывести числаНазад.получить(2)
}
`)
	wantLines := []string{
		"Аня <А>", "30", "истина", "Москва", "2", "б & в", "3", "3",
	}
	for _, want := range wantLines {
		if !strings.Contains(got, want) {
			t.Fatalf("ожидалось вхождение %q в вывод, получено:\n%s", want, got)
		}
	}
}

func TestRunXMLMissingFieldThrowsCatchable(t *testing.T) {
	got := runSrc(t, `
сущность Пользователь
{
    имеет:
        имя: Строка
}
функция главная
{
    попытаться {
        переменная п = разобрать XML "<значение></значение>" как Пользователь
        вывести "не должно"
    } поймать(иск: ОшибкаРазбора) {
        вывести иск.сообщение
    }
}
`)
	want := "разобрать XML: отсутствует поле \"имя\"\n"
	if got != want {
		t.Fatalf("получили %q, хотели %q", got, want)
	}
}

