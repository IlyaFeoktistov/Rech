// TestRunXMLAttributesAndRenamedElements - "xml:имя" переименовывает
// дочерний элемент, "xml:@имя"/"xml:@" - атрибут; значение атрибута
// раскрывает сущности при разборе и экранирует кавычку при сериализации.
func TestRunXMLAttributesAndRenamedElements(t *testing.T) {
	got := runSrc(t, `
сущность Товар
{
    имеет:
        Целое ид `+"`xml:@id`"+`
        Строка валюта `+"`xml:@`"+`
        Строка название `+"`xml:title`"+`
        Список<Строка> теги `+"`xml:tag`"+`
}
функция главная
{
    переменная т = разобрать XML `+"`"+`<товар id="7" валюта='R&quot;B'><title>Чай</title><tag>a</tag><tag>b</tag></товар>`+"`"+` как Товар
    вывести `+"`${"+`т.ид} ${т.валюта} ${т.название} ${т.теги.длина()}\n`+"`"+`
    вывести `+"`${"+`сериализовать XML т}\n`+"`"+`
}
`)
	want := "7 R\"B Чай 2\n" + `<значение id="7" валюта="R&quot;B"><title>Чай</title><tag>a</tag><tag>b</tag></значение>` + "\n"
	if got != want {
		t.Fatalf("ожидалось %q, получено %q", want, got)
	}
}

