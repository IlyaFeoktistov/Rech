func TestRunXMLRoundTripEntityListPrimitives(t *testing.T) {
	got := runSrc(t, `
сущность Адрес
{
    имеет:
        Строка город
}
сущность Пользователь
{
    имеет:
        Строка имя
        Целое возраст
        Логическое активен
        Адрес адрес
        Список<Строка> теги
}
функция главная
{
    переменная адрес = новый Адрес()
    адрес.город = "Москва"
    переменная теги = новый Список<Строка>()
    теги.добавить("а")
    теги.добавить("б & в")
    переменная п = новый Пользователь()
    п.имя = "Аня <А>"
    п.возраст = 30
    п.активен = истина
    п.адрес = адрес
    п.теги = теги
    переменная текст = сериализовать XML п
    вывести `+"`${"+`текст}\n`+"`"+`

    переменная восстановленный = разобрать XML текст как Пользователь
    вывести `+"`${"+`восстановленный.имя}\n`+"`"+`
    вывести `+"`${"+`восстановленный.возраст}\n`+"`"+`
    вывести `+"`${"+`восстановленный.активен}\n`+"`"+`
    вывести `+"`${"+`восстановленный.адрес.город}\n`+"`"+`
    вывести `+"`${"+`восстановленный.теги.длина()}\n`+"`"+`
    вывести `+"`${"+`восстановленный.теги.получить(1)}\n`+"`"+`

    переменная числа = новый Список<Целое>()
    числа.добавить(1)
    числа.добавить(2)
    числа.добавить(3)
    переменная числаТекст = сериализовать XML числа
    переменная числаНазад = разобрать XML числаТекст как Список<Целое>
    вывести `+"`${"+`числаНазад.длина()}\n`+"`"+`
    вывести `+"`${"+`числаНазад.получить(2)}\n`+"`"+`
}
`)
	wantLines := []string{
		"Аня <А>", "30", "истина", "Москва", "2", "б & в", "3", "3",
	}
	for _, want := range wantLines {
		if !strings.Contains(got, want) {
			t.Fatalf("ожидалось вхождение %q в вывод, получено:\n%s", want, got)
		}
	}
}

