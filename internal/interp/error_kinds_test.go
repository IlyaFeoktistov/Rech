// Непойманное встроенное исключение - тот же текст, что у cbackend.
func TestBuiltinErrorUncaughtMessage(t *testing.T) {
	err := runSrcExpectRuntimeError(t, "функция главная\n{\n    Файл ф = открыть(\"/нет/такого/файла\")\n}\n")
	const want = "необработанное исключение ОшибкаФайла: открыть: не удалось открыть файл \"/нет/такого/файла\""
	if !strings.Contains(err.Error(), want) {
		t.Fatalf("ожидалась ошибка %q, получено: %v", want, err)
	}
}
