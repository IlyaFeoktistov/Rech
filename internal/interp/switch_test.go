package interp

import "testing"

// TestRunSwitchNoMatchWithoutDefaultDoesNothing - "выбрать" без "иначе" и
// без совпавшей ветки просто ничего не делает (см. docs/SPEC.md, раздел
// "выбрать"/"когда").
func TestRunSwitchNoMatchWithoutDefaultDoesNothing(t *testing.T) {
	got := runSrc(t, `
функция главная
{
    переменная число = 99
    выбрать число
    {
        когда 1:
            вывести "один\n"
    }
    вывести "после\n"
}
`)
	if got != "после\n" {
		t.Fatalf("ожидался только вывод \"после\", получено %q", got)
	}
}

// TestRunSwitchBranchesDoNotFallThrough - совпавшая ветка не проваливается
// в следующую (нет "break", в отличие от C) - выполняется РОВНО одна.
func TestRunSwitchBranchesDoNotFallThrough(t *testing.T) {
	got := runSrc(t, `
функция главная
{
    переменная число = 1
    выбрать число
    {
        когда 1:
            вывести "один\n"
        когда 2:
            вывести "два\n"
        иначе:
            вывести "другое\n"
    }
}
`)
	if got != "один\n" {
		t.Fatalf("ожидался только вывод \"один\", получено %q", got)
	}
}

// TestRunSwitchSubjectEvaluatedOnce - "выбрать <выражение>" вычисляет
// <выражение> РОВНО один раз, даже если ни одна ветка не совпадает и
// пришлось проверить их все - иначе вызов с побочным эффектом в подлежащем
// выполнился бы повторно на каждой проверке.
func TestRunSwitchSubjectEvaluatedOnce(t *testing.T) {
	got := runSrc(t, `
функция считать(): Целое
{
    статическая переменная счёт = 0
    счёт = счёт + 1
    вернуть счёт
}

функция главная
{
    выбрать считать()
    {
        когда 100:
            вывести "сто\n"
        когда 200:
            вывести "двести\n"
        иначе:
            вывести "другое\n"
    }
    вывести `+"`${"+`считать()}\n`+"`"+`
}
`)
	if got != "другое\n2\n" {
		t.Fatalf("ожидалось ровно одно вычисление подлежащего на проверку веток (второй считать() == 2), получено %q", got)
	}
}
