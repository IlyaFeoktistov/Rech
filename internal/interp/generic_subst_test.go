package interp

import "testing"

// Параметр типа подставляется во всех позициях тела generic-функции:
// объявление с типом первым, "?T", "новый Список<T>", Словарь<Строка, T>,
// тип лямбды, "как T". Вывод совпадает с cbackend.
func TestGenericFunctionBodyTypeSubstitution(t *testing.T) {
	const want = "1 5 5 [5]\n1 текст текст [текст]\n"
	if got := runSrc(t, `функция обработать<T>(значение: T): Строка
{
    Список<T> список = новый Список<T>()
    список.добавить(значение)
    Словарь<Строка, T> словарь = новый Словарь<Строка, T>()
    словарь.установить("к", значение)
    ?T может = значение
    Вызываемый(T): Строка преобразовать = функция (x: T): Строка { вернуть `+"`"+`[${x}]`+"`"+` }
    Значение з = (Значение) значение
    T обратно = з как T
    переменная явно: T = обратно
    вернуть `+"`"+`${список.длина()} ${словарь.получить("к")} ${может ?? значение} ${преобразовать(явно)}`+"`"+`
}

функция главная
{
    вывести `+"`"+`${обработать<Целое>(5)}\n`+"`"+`
    вывести `+"`"+`${обработать("текст")}\n`+"`"+`
}
`); got != want {
		t.Fatalf("хотели %q, получили %q", want, got)
	}
}
