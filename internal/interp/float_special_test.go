package interp

import "testing"

// Бесконечность/NaN и их проверки - тот же вывод, что и у cbackend (NaN
// без знака даже у 0.0/0.0).
func TestFloatInfinityAndNaN(t *testing.T) {
	const want = "inf -inf nan inf nan\nистина истина ложь истина ложь истина\n"
	if got := runSrc(t, `функция главная
{
    Действительное б = Действительное::БЕСКОНЕЧНОСТЬ
    Действительное н = Действительное::НЕ_ЧИСЛО
    Дробное д = Дробное::БЕСКОНЕЧНОСТЬ
    Действительное ноль = 0.0
    вывести `+"`"+`${б} ${-б} ${н} ${д} ${ноль / ноль}\n`+"`"+`
    вывести `+"`"+`${б.бесконечно()} ${н.не_число()} ${н == н} ${(1.5).конечно()} ${д.конечно()} ${не_число(н)}\n`+"`"+`
}
`); got != want {
		t.Fatalf("хотели %q, получили %q", want, got)
	}
}

// Арифметика и функции на бесконечности/NaN - по IEEE 754, как у C;
// минимум/максимум пропускают NaN (fmin/fmax).
func TestFloatInfinityArithmeticLaws(t *testing.T) {
	const want = "inf inf -inf 0 -0\nnan nan nan nan\nистина истина ложь истина ложь\ninf 0 -inf nan 1.5707963267948966\n1 1 inf\n"
	if got := runSrc(t, `функция главная
{
    Действительное б = Действительное::БЕСКОНЕЧНОСТЬ
    Действительное н = Действительное::НЕ_ЧИСЛО
    вывести `+"`"+`${б + 1.0} ${б + б} ${-б * 3.0} ${1.0 / б} ${-1.0 / б}\n`+"`"+`
    вывести `+"`"+`${б - б} ${0.0 * б} ${б / б} ${н + 1.0}\n`+"`"+`
    вывести `+"`"+`${б > 1.0e308} ${б == б} ${н == н} ${н != н} ${н < 1.0}\n`+"`"+`
    вывести `+"`"+`${экспонента(б)} ${экспонента(-б)} ${логарифм(0.0)} ${корень(-1.0)} ${арктангенс(б)}\n`+"`"+`
    вывести `+"`"+`${максимум(н, 1.0)} ${минимум(1.0, н)} ${максимум(б, 1.0)}\n`+"`"+`
}
`); got != want {
		t.Fatalf("хотели %q, получили %q", want, got)
	}
}
