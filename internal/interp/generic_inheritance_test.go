package interp

import "testing"

// generic-сущность наследует и реализует; база - инстанциация generic
// ("наследует Коробку<T>", "наследует Коробку<Целое>"); "относится к" с
// generic-типом. Вывод совпадает с cbackend.
func TestGenericEntityInheritance(t *testing.T) {
	const want = "метка: текст\nкоробка 3\n42 истина истина\nкоробка 21\nсемь: 7\n"
	if got := runSrc(t, `интерфейс Описываемый
{
    описание(): Строка
}

сущность Коробка<T> реализует Описываемый
{
    имеет:
        публичное значение: T

    конструктор(значение: T)
    {
        этот.значение = значение
    }

    публичный описание(): Строка
    {
        вернуть `+"`"+`коробка ${этот.значение}`+"`"+`
    }
}

сущность Подписанная<T> наследует Коробку<T>
{
    имеет:
        публичная подпись: Строка

    конструктор(значение: T, подпись: Строка)
    {
        родитель(значение)
        этот.подпись = подпись
    }

    публичный описание(): Строка
    {
        вернуть `+"`"+`${этот.подпись}: ${этот.значение}`+"`"+`
    }
}

сущность ЦелаяКоробка наследует Коробку<Целое>
{
    конструктор(значение: Целое)
    {
        родитель(значение)
    }

    публичный удвоить(): Целое
    {
        вернуть этот.значение * 2
    }
}

функция отобразить(о: Описываемый)
{
    вывести `+"`"+`${о.описание()}\n`+"`"+`
}

функция главная
{
    Подписанная<Строка> п = новая Подписанная<Строка>("текст", "метка")
    Коробка<Строка> база = п
    отобразить(база)
    отобразить(новая Коробка<Целое>(3))
    ЦелаяКоробка ц = новая ЦелаяКоробка(21)
    вывести `+"`"+`${ц.удвоить()} ${ц относится к Коробка<Целое>} ${база относится к Подписанная<Строка>}\n`+"`"+`
    отобразить(ц)
    Подписанная<Целое> пц = новая Подписанная<Целое>(7, "семь")
    отобразить(пц)
}
`); got != want {
		t.Fatalf("хотели %q, получили %q", want, got)
	}
}
