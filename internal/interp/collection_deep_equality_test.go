package interp

import "testing"

// TestRunListEqualComparesContent - "равен" у "Список<T>"
// - глубокое сравнение содержимого, в отличие от "==" (identity, см.
// TestRunEntityEqualityComparesByReference по тому же принципу у
// сущности/класса).
func TestRunListEqualComparesContent(t *testing.T) {
	got := runSrc(t, `
функция главная
{
    переменная а = [1, 2, 3]
    переменная б = [1, 2, 3]
    переменная г = [1, 2, 4]
    вывести `+"`${"+`а == б}\n`+"`"+`
    вывести `+"`${"+`а.равен(б)}\n`+"`"+`
    вывести `+"`${"+`а.равен(г)}\n`+"`"+`
}
`)
	if got != "ложь\nистина\nложь\n" {
		t.Fatalf("получили %q", got)
	}
}

// TestRunListEqualNestedListComparesRecursively - элемент сам Список<T> -
// "равен" внешнего списка рекурсивно зовёт "равен" вложенного, а не
// сравнивает его identity (иначе метод был бы бесполезен ровно для того
// случая, ради которого его завели).
func TestRunListEqualNestedListComparesRecursively(t *testing.T) {
	got := runSrc(t, `
функция главная
{
    переменная а = [[1, 2], [3, 4]]
    переменная б = [[1, 2], [3, 4]]
    переменная г = [[1, 2], [3, 5]]
    вывести `+"`${"+`а.равен(б)}\n`+"`"+`
    вывести `+"`${"+`а.равен(г)}\n`+"`"+`
}
`)
	if got != "истина\nложь\n" {
		t.Fatalf("получили %q", got)
	}
}

// TestRunDictEqualIgnoresInsertionOrder - "равен" у "Словарь<К, В>"
// сравнивает по ключам (хеш-таблица неупорядочена) - тот же набор пар в
// другом порядке вставки всё ещё равен.
func TestRunDictEqualIgnoresInsertionOrder(t *testing.T) {
	got := runSrc(t, `
функция главная
{
    переменная а = новый Словарь<Строка, Целое>()
    а.установить("x", 1)
    а.установить("y", 2)

    переменная б = новый Словарь<Строка, Целое>()
    б.установить("y", 2)
    б.установить("x", 1)

    вывести `+"`${"+`а.равен(б)}\n`+"`"+`

    б.установить("y", 9)
    вывести `+"`${"+`а.равен(б)}\n`+"`"+`
}
`)
	if got != "истина\nложь\n" {
		t.Fatalf("получили %q", got)
	}
}
