package interp

import "testing"

// TestRunOverloadOverInheritedMethod - перегрузки потомка объединяются с
// вариантами базовой; вариант с той же сигнатурой - переопределение,
// вызов через базовый тип диспетчеризуется в потомка.
func TestRunOverloadOverInheritedMethod(t *testing.T) {
	got := runSrc(t, `сущность Фигура
{
    публичный описать(): Строка
    {
        вернуть "фигура"
    }

    публичный масштаб(раз: Целое): Строка
    {
        вернуть `+"`"+`фигура целое ${раз}`+"`"+`
    }

    публичный масштаб(раз: Действительное): Строка
    {
        вернуть "фигура дробь"
    }
}

сущность Круг наследует Фигуру
{
    // перегрузка поверх обычного базового: переопределение + новый вариант
    публичный описать(): Строка
    {
        вернуть "круг"
    }

    публичный описать(подробно: Логическое): Строка
    {
        вернуть подробно ? "круг подробно" : "круг"
    }

    // одиночный метод поверх базовой группы: переопределяет вариант Целое
    публичный масштаб(раз: Целое): Строка
    {
        вернуть `+"`"+`круг целое ${раз}`+"`"+`
    }
}

сущность Квадрат наследует Фигуру
{
    // одиночный метод поверх базовой группы: новый вариант
    публичный масштаб(раз: Строка): Строка
    {
        вернуть `+"`"+`квадрат строка ${раз}`+"`"+`
    }

    // одиночный метод поверх обычного: другие параметры - перегрузка
    публичный описать(имя: Строка): Строка
    {
        вернуть `+"`"+`квадрат ${имя}`+"`"+`
    }
}

функция главная
{
    переменная круг = новый Круг()
    вывести `+"`"+`${круг.описать()} | ${круг.описать(истина)} | ${круг.масштаб(2)} | ${круг.масштаб(1.5)}\n`+"`"+`
    переменная ф: Фигура = круг
    вывести `+"`"+`${ф.описать()} | ${ф.масштаб(3)} | ${ф.масштаб(1.5)}\n`+"`"+`
    переменная кв = новый Квадрат()
    вывести `+"`"+`${кв.описать()} | ${кв.описать("А")} | ${кв.масштаб(4)} | ${кв.масштаб("x")}\n`+"`"+`
    переменная ф2: Фигура = кв
    вывести `+"`"+`${ф2.описать()} | ${ф2.масштаб(5)}\n`+"`"+`
}
`)
	want := "круг | круг подробно | круг целое 2 | фигура дробь\n" +
		"круг | круг целое 3 | фигура дробь\n" +
		"фигура | квадрат А | фигура целое 4 | квадрат строка x\n" +
		"фигура | фигура целое 5\n"
	if got != want {
		t.Fatalf("получили %q, ожидали %q", got, want)
	}
}

// TestRunOverloadOverInheritedMethodChain - три уровня: обычный метод
// базовой, перегрузка в середине, переопределение обоих вариантов внизу.
func TestRunOverloadOverInheritedMethodChain(t *testing.T) {
	got := runSrc(t, `сущность А
{
    публичный м(): Строка
    {
        вернуть "А.м()"
    }
}

сущность Б наследует А
{
    публичный м(х: Целое): Строка
    {
        вернуть `+"`"+`Б.м(${х})`+"`"+`
    }
}

сущность В наследует Б
{
    публичный м(): Строка
    {
        вернуть "В.м()"
    }

    публичный м(х: Целое): Строка
    {
        вернуть `+"`"+`В.м(${х})`+"`"+`
    }
}

функция главная
{
    переменная а: А = новый В()
    переменная б: Б = новый В()
    переменная бб: Б = новый Б()
    вывести `+"`"+`${а.м()} ${б.м()} ${б.м(1)} ${бб.м()} ${бб.м(2)}\n`+"`"+`
}
`)
	want := "В.м() В.м() В.м(1) А.м() Б.м(2)\n"
	if got != want {
		t.Fatalf("получили %q, ожидали %q", got, want)
	}
}
