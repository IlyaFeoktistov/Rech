package interp

import "testing"

// TestOverloadedMethodsResolveDistinctBodies - метод сущности, перегруженный
// по типу и по количеству параметров, исполняется как РАЗНЫЕ реализации в
// зависимости от аргументов вызова (см. internal/semantic/overload.go).
func TestOverloadedMethodsResolveDistinctBodies(t *testing.T) {
	out := runSrc(t, `
сущность Калькулятор
{
    сложить(а: Целое, б: Целое): Целое
    {
        вернуть а + б
    }
    сложить(а: Строка, б: Строка): Строка
    {
        вернуть а + б
    }
    сложить(а: Целое, б: Целое, ц: Целое): Целое
    {
        вернуть а + б + ц
    }
}
функция главная
{
    переменная калькулятор = новый Калькулятор()
    вывести калькулятор.сложить(2, 3)
    вывести калькулятор.сложить("привет, ", "мир")
    вывести калькулятор.сложить(1, 2, 3)
}
`)
	want := "5\nпривет, мир\n6\n"
	if out != want {
		t.Fatalf("ожидался вывод %q, получено %q", want, out)
	}
}
