func TestDBTransactionCommitsOnNormalReturn(t *testing.T) {
	out := runSrc(t, `
функция главная
{
    переменная бд = подключиться_к_бд("sqlite::memory:")
    выполнить(бд, "create table t(id integer)", новый Список<Значение>())
    начать_транзакцию(бд, функция(тр: Транзакция)
    {
        переменная параметры = новый Список<Значение>()
        параметры.добавить((Значение) 1)
        тр.выполнить("INSERT INTO t (id) VALUES (?)", параметры)
        переменная параметры2 = новый Список<Значение>()
        параметры2.добавить((Значение) 2)
        тр.выполнить("INSERT INTO t (id) VALUES (?)", параметры2)
    })
    переменная строки = запросить(бд, "select id from t", новый Список<Значение>())
    вывести `+"`${"+`строки.длина()}\n`+"`"+`
    закрыть_бд(бд)
}
`)
	if out != "2\n" {
		t.Fatalf("ожидалось \"2\\n\", получено %q", out)
	}
}

