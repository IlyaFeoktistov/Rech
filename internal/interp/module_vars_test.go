package interp

import "testing"

// TestModuleVarsInterp - значения переменных модуля вычисляются до
// "главная" по порядку; их меняют функции и лямбды; локальная переменная с
// тем же именем перекрывает переменную модуля.
func TestModuleVarsInterp(t *testing.T) {
	src := `Целое счётчик = 0
Список<Строка> журнал = []
Целое удвоенное = 21 * 2

функция отметить(что: Строка)
{
    счётчик++
    журнал.добавить(что)
}

функция главная
{
    отметить("а")
    отметить("б")
    Вызываемый() ф = функция() {
        счётчик += 10
    }
    ф()
    Целое удвоенное = 7
    вывести ` + "`${счётчик} ${журнал.длина()} ${удвоенное}\\n`" + `
}
`
	if got, want := runSrc(t, src), "12 2 7\n"; got != want {
		t.Fatalf("получено %q, ожидалось %q", got, want)
	}
}

// TestReflectionSeesBuiltinSynonymsAsOneType - "тип Натуральное8" и "тип
// Байт" (а также "Целое64"/"Целое") - один тип: одно имя, упакованный Байт
// распаковывается "как Натуральное8".
func TestReflectionSeesBuiltinSynonymsAsOneType(t *testing.T) {
	src := `функция главная
{
    Байт б = 200
    Значение коробка = (Значение) б
    Натуральное8 обратно = коробка как Натуральное8
    переменная т8 = тип Натуральное8
    вывести ` + "`${т8.имя()} ${(тип Байт).имя()} ${(тип Целое64).имя()} ${коробка.тип_значения().имя()} ${обратно}\\n`" + `
}
`
	if got, want := runSrc(t, src), "Байт Байт Целое Байт 200\n"; got != want {
		t.Fatalf("получено %q, ожидалось %q", got, want)
	}
}
