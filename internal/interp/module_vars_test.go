package interp

import "testing"

// TestModuleVarsInterp - значения переменных модуля вычисляются до
// "главная" по порядку; их меняют функции и лямбды; локальная переменная с
// тем же именем перекрывает переменную модуля.
func TestModuleVarsInterp(t *testing.T) {
	src := `Целое счётчик = 0
Список<Строка> журнал = []
Целое удвоенное = 21 * 2

функция отметить(что: Строка)
{
    счётчик++
    журнал.добавить(что)
}

функция главная
{
    отметить("а")
    отметить("б")
    Вызываемый() ф = функция() {
        счётчик += 10
    }
    ф()
    Целое удвоенное = 7
    вывести ` + "`${счётчик} ${журнал.длина()} ${удвоенное}\\n`" + `
}
`
	if got, want := runSrc(t, src), "12 2 7\n"; got != want {
		t.Fatalf("получено %q, ожидалось %q", got, want)
	}
}
