package interp

import "testing"

// TestRunSelfReturnChainsThroughInheritedMethod - тот же сценарий, что и
// internal/semantic/self_return_test.go
// (TestAnalyzeSelfReturnInheritedMethodResolvesToDerivedEntityAtCallSite),
// но с реальным исполнением: базовый метод с "этот" как типом результата,
// унаследованный без переопределения, даёт объект, у которого можно
// вызвать метод, объявленный только у производной сущности.
func TestRunSelfReturnChainsThroughInheritedMethod(t *testing.T) {
	got := runSrc(t, `
сущность СтроительА
{
    имеет:
        имя_поле: Строка

    задать_имя(значение: Строка): этот
    {
        этот.имя_поле = значение
        вернуть этот
    }
}
сущность СтроительБ наследует СтроительА
{
    имеет:
        доп_поле: Целое

    конструктор(имя_поле: Строка, доп_поле: Целое)
    {
        этот.имя_поле = имя_поле
        этот.доп_поле = доп_поле
    }

    задать_доп(значение: Целое): этот
    {
        этот.доп_поле = значение
        вернуть этот
    }
}
функция главная
{
    переменная б = новый СтроительБ("", 0)
    переменная б2 = б.задать_имя("х")
    б2.задать_доп(5)
    вывести `+"`${"+`б.имя_поле}\n`+"`"+`
    вывести `+"`${"+`б.доп_поле}\n`+"`"+`
}
`)
	if got != "х\n5\n" {
		t.Fatalf("ожидалась мутация того же объекта через цепочку self-возвратов, получили %q", got)
	}
}

// TestRunSelfReturnThroughInterfaceMutatesUnderlyingObject - вызов метода с
// "этот" как типом результата через интерфейсное значение - мутация видна
// через оригинальную переменную конкретного типа (тот же объект).
func TestRunSelfReturnThroughInterfaceMutatesUnderlyingObject(t *testing.T) {
	got := runSrc(t, `
интерфейс Именуемый
{
    задать_имя(значение: Строка): этот
}
сущность Штука реализует Именуемый
{
    имеет:
        имя_поле: Строка

    конструктор(имя_поле: Строка)
    {
        этот.имя_поле = имя_поле
    }

    задать_имя(значение: Строка): этот
    {
        этот.имя_поле = значение
        вернуть этот
    }
}
функция настроить(х: Именуемый)
{
    х.задать_имя("х")
}
функция главная
{
    переменная ш = новая Штука("")
    настроить(ш)
    вывести `+"`${"+`ш.имя_поле}\n`+"`"+`
}
`)
	if got != "х\n" {
		t.Fatalf("ожидалась мутация объекта через интерфейсный вызов, получили %q", got)
	}
}
