package interp

import "testing"

// TestRunNullableCollectionElements - "?Тип" элементом Список/Стопка/
// Очередь и значением Словарь: добавление Ничто и обычного значения,
// перебор с сужением, "получить" - "?T", "[]" без повторной обёртки.
func TestRunNullableCollectionElements(t *testing.T) {
	got := runSrc(t, `функция главная()
{
    Список<?Целое> числа = новый Список<?Целое>()
    числа.добавить(1)
    числа.добавить(Ничто)
    числа.добавить(3)
    вывести `+"`"+`${числа.длина()}\n`+"`"+`
    для ч в числах {
        если ч != Ничто {
            вывести `+"`"+`есть ${ч}\n`+"`"+`
        } иначе {
            вывести `+"`"+`пусто\n`+"`"+`
        }
    }
    ?Целое второй = числа.получить(1)
    вывести `+"`"+`${второй ?? -1}\n`+"`"+`
    вывести `+"`"+`${числа[0] ?? -1} ${числа[1] ?? -2} ${числа[9] ?? -3}\n`+"`"+`
}
`)
	want := "3\nесть 1\nпусто\nесть 3\n-1\n1 -2 -3\n"
	if got != want {
		t.Fatalf("получили %q, ожидали %q", got, want)
	}
}

// TestRunNullableCollectionLiteralsAndEquality - литерал с Ничто выводит
// "Список<?T>", "?Сущность"/"?Список<T>" элементом, "показать" и "равен".
func TestRunNullableCollectionLiteralsAndEquality(t *testing.T) {
	got := runSrc(t, `сущность Точка
{
    имеет:
        Целое x

    конструктор(x: Целое)
    {
        этот.x = x
    }
}

функция главная()
{
    переменная а = [1, Ничто, 3]
    а.установить(0, Ничто)
    а[2] = 30
    вывести `+"`"+`${а.длина()} ${а[0] ?? -1} ${а[2] ?? -1}\n`+"`"+`

    Словарь<Строка, ?Строка> имена = новый Словарь<Строка, ?Строка>()
    имена.установить("ваня", "Иван")
    имена.установить("никто", Ничто)
    вывести `+"`"+`${имена["ваня"] ?? "-"} ${имена["никто"] ?? "-"} ${имена["нет"] ?? "-"} ${имена.содержит("никто")}\n`+"`"+`

    Стопка<?Точка> стопка = новая Стопка<?Точка>()
    стопка.положить(новая Точка(5))
    стопка.положить(Ничто)
    ?Точка верх = стопка.снять()
    вывести `+"`"+`${верх == Ничто}\n`+"`"+`
    ?Точка т = стопка.снять()
    если т != Ничто {
        вывести `+"`"+`${т.x}\n`+"`"+`
    }

    Очередь<?Список<Целое>> очередь = новая Очередь<?Список<Целое>>()
    очередь.добавить([1, 2])
    очередь.добавить(Ничто)
    ?Список<Целое> первый = очередь.извлечь()
    если первый != Ничто {
        вывести `+"`"+`${первый.длина()}\n`+"`"+`
    }

    показать а
    показать имена
    Список<?Целое> б = [Ничто, Ничто, 30]
    вывести `+"`"+`${а.равен(б)}\n`+"`"+`
}
`)
	want := "3 -1 30\nИван - - истина\nистина\n5\n2\n" +
		"Список<?Целое> [Ничто (?Целое), Ничто (?Целое), 30 (Целое)]\n" +
		"Словарь<Строка, ?Строка> {\"ваня\" (Строка): \"Иван\" (Строка), \"никто\" (Строка): Ничто (?Строка)}\n" +
		"истина\n"
	if got != want {
		t.Fatalf("получили %q, ожидали %q", got, want)
	}
}

// TestRunNullableCollectionStructCallableField - "?структура" элементом
// ("равен" рекурсивно по полям), "?Вызываемый" элементом, Список<?Строка>
// полем сущности.
func TestRunNullableCollectionStructCallableField(t *testing.T) {
	got := runSrc(t, `структура Пара
{
    имеет:
        Целое а
        Целое б
}

сущность Журнал
{
    имеет:
        Список<?Строка> записи

    конструктор()
    {
        этот.записи = [Ничто, "x"]
    }
}

функция удвоить(х: Целое): Целое
{
    вернуть х * 2
}

функция главная
{
    Список<?Пара> пары = новый Список<?Пара>()
    пары.добавить(новая Пара(1, 2))
    пары.добавить(Ничто)
    Список<?Пара> копия = [новая Пара(1, 2), Ничто]
    вывести `+"`"+`${пары.равен(копия)}\n`+"`"+`

    Список<?Вызываемый(Целое): Целое> ф = новый Список<?Вызываемый(Целое): Целое>()
    ф.добавить(&удвоить)
    ф.добавить(Ничто)
    для фн в ф {
        если фн != Ничто {
            вывести `+"`"+`есть\n`+"`"+`
        } иначе {
            вывести `+"`"+`нет\n`+"`"+`
        }
    }
    переменная ж = новый Журнал()
    вывести `+"`"+`${ж.записи.длина()} ${ж.записи[1] ?? "-"}\n`+"`"+`
}
`)
	want := "истина\nесть\nнет\n2 x\n"
	if got != want {
		t.Fatalf("получили %q, ожидали %q", got, want)
	}
}
