package interp

import "testing"

func TestRunThrowCatchSingleTypeBindsMessage(t *testing.T) {
	out := runSrc(t, `
функция главная
{
    попытаться {
        выбросить новое Исключение("что-то пошло не так")
    } поймать(иск: Исключение) {
        вывести иск.сообщение
    }
}
`)
	if out != "что-то пошло не так\n" {
		t.Fatalf("ожидалось \"что-то пошло не так\", получено %q", out)
	}
}

