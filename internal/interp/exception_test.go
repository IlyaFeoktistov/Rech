func TestRunUncaughtThrowReturnsError(t *testing.T) {
	err := runSrcExpectRuntimeError(t, `
функция главная
{
    выбросить новое Исключение("необработано")
}
`)
	if err == nil {
		t.Fatalf("ожидалась ошибка - необработанное исключение")
	}
	if got := err.Error(); got != "выполнение прервано: необработанное исключение Исключение: необработано" {
		t.Fatalf("неожиданный текст ошибки: %q", got)
	}
}
