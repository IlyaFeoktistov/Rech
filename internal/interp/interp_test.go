// TestRunCallsExternFuncCallbackArg - "Вызываемый(...)" параметром внешней
// функции (qsort - настоящий колбэк из C). НЕ через examples/основы/
// колбэк_из_c.rech (atexit) - тот пример не резолвится интерпретатором:
// на этой машине (glibc) "atexit" не экспортирован как динамический символ
// libc.so.6 (nm -D показывает только __cxa_atexit) - настоящий "atexit"
// живёт в libc_nonshared.a, статическом архиве, который линкер cc
// подтягивает автоматически при компиляции, но которого нет в динамической
// таблице символов для dlopen/dlsym (фундаментальное ограничение
// dlopen-based FFI, не баг этого файла - см. docs/SPEC.md, раздел 12).
// Сколько именно раз comparator вызывается для 5-элементного буфера "всё
// равно" - деталь РЕАЛИЗАЦИИ qsort конкретной libc, не языка (glibc - 5
// раз, Windows UCRT - 10 - живая находка на настоящей Windows через WSL,
// не баг колбэка) - тест поэтому не сверяет точное число, только что
// вызовов хотя бы один и счётчик растёт на 1 каждый раз.
func TestRunCallsExternFuncCallbackArg(t *testing.T) {
	got := runSrc(t, `
внешняя сущность void как Блок
внешняя функция malloc как выделить(размер: Целое): Блок
внешняя функция free как освободить(блок: Блок)
внешняя функция qsort(база: Блок, количество: Целое, размер: Целое, сравнить: Вызываемый(Блок, Блок): Целое)

функция главная
{
	переменная буфер = выделить(40)
	переменная вызовов = 0
	qsort(буфер, 5, 8, функция (a: Блок, b: Блок): Целое {
		вызовов = вызовов + 1
		вывести `+"`${"+`вызовов}\n`+"`"+`
		вернуть 0
	})
	освободить(буфер)
	вывести `+"`"+`готово\n`+"`"+`
}
`)
	if !strings.HasSuffix(got, "готово\n") {
		t.Fatalf("ожидалось \"готово\" последней строкой, получено %q", got)
	}
	counts := strings.Split(strings.TrimSuffix(got, "готово\n"), "\n")
	counts = counts[:len(counts)-1] // TrimSuffix оставляет пустую строку последней
	if len(counts) == 0 {
		t.Fatalf("comparator ни разу не вызван, получено %q", got)
	}
	for i, line := range counts {
		want := strconv.Itoa(i + 1)
		if line != want {
			t.Fatalf("вызов %d: получено %q, ожидалось %q (счётчик должен расти на 1 с каждым вызовом)", i+1, line, want)
		}
	}
}

// TestRunPlatformBlock - "#если ОС.<Член> { ... }" (docs/SPEC.md) -
// разрешается ДО семантического анализа (internal/ast.
// ResolvePlatformBlocks, вызвана из semantic.Analyze - runSrc не проходит
// через internal/module, поэтому нужен именно этот путь, см. package doc
// semantic.Analyze) - руки, не подошедшие под текущую платформу, не
// попадают в программу вовсе: если бы попадали, "сообщение" была бы
// объявлена трижды - ошибка "уже объявлена", не то, что видно в этом
// тесте. Ожидаемая ветка зависит от платформы, на которой реально
// исполняется тест (runtime.GOOS) - тот же принцип, что и у
// windowsWantOverrides выше (сама фича платформозависима по определению).
func TestRunPlatformBlock(t *testing.T) {
	got := runSrc(t, `
#если ОС.Linux {
	функция сообщение(): Строка { вернуть "linux-ветка" }
} #иначе если ОС.Windows {
	функция сообщение(): Строка { вернуть "windows-ветка" }
} #иначе {
	функция сообщение(): Строка { вернуть "macos-ветка" }
}

функция главная { вывести (Строка) (сообщение()) + `+"`"+`\n`+"`"+` }
`)
	want := "linux-ветка\n"
	switch runtime.GOOS {
	case "windows":
		want = "windows-ветка\n"
	case "darwin":
		want = "macos-ветка\n"
	}
	if got != want {
		t.Fatalf("получено %q, ожидалось %q", got, want)
	}
}

