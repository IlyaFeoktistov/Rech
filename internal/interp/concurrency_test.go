package interp

import "testing"

func TestRunLaunchAwaitReturnsResult(t *testing.T) {
	out := runSrc(t, `
функция посчитать(а: Целое, б: Целое): Целое
{
    вернуть а + б
}
функция главная
{
    переменная задача = запустить посчитать(2, 3)
    переменная результат = дождаться задача
    вывести результат
}
`)
	if out != "5\n" {
		t.Fatalf("ожидалось \"5\", получено %q", out)
	}
}

func TestRunAwaitWithoutReturnAsStatement(t *testing.T) {
	out := runSrc(t, `
функция поработать()
{
    вывести "работаю"
}
функция главная
{
    переменная задача = запустить поработать()
    дождаться задача
    вывести "готово"
}
`)
	if out != "работаю\nготово\n" {
		t.Fatalf("ожидалось \"работаю\\nготово\\n\", получено %q", out)
	}
}

func TestRunUncaughtExceptionInTaskRethrownAtAwaitAndCatchable(t *testing.T) {
	out := runSrc(t, `
сущность ОшибкаВвода наследует Исключение
{
    конструктор(сообщение: Строка)
    {
        родитель(сообщение)
    }
}
функция сломать()
{
    выбросить новая ОшибкаВвода("не удалось")
}
функция главная
{
    переменная задача = запустить сломать()
    попытаться {
        дождаться задача
    } поймать(иск: ОшибкаВвода) {
        вывести "поймано: "
        вывести иск.сообщение
    }
}
`)
	if out != "поймано: \nне удалось\n" {
		t.Fatalf("ожидалось \"поймано: \\nне удалось\\n\", получено %q", out)
	}
}

func TestRunLaunchArgsAreClonedNotSharedWithCaller(t *testing.T) {
	out := runSrc(t, `
функция ждать_поле(т: Точка): Целое
{
    вернуть т.x
}
структура Точка
{
    имеет:
        x: Целое
}
функция главная
{
    переменная т = новая Точка(1)
    переменная задача = запустить ждать_поле(т)
    т.x = 99
    переменная результат = дождаться задача
    вывести результат
}
`)
	if out != "1\n" {
		t.Fatalf("ожидалось \"1\" (структура клонируется на границе горутины), получено %q", out)
	}
}

func TestRunMultipleConcurrentTasks(t *testing.T) {
	out := runSrc(t, `
функция удвоить(х: Целое): Целое
{
    вернуть х * 2
}
функция главная
{
    переменная задача1 = запустить удвоить(1)
    переменная задача2 = запустить удвоить(2)
    переменная задача3 = запустить удвоить(3)
    вывести дождаться задача1
    вывести дождаться задача2
    вывести дождаться задача3
}
`)
	if out != "2\n4\n6\n" {
		t.Fatalf("ожидалось \"2\\n4\\n6\\n\", получено %q", out)
	}
}
