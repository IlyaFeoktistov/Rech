func TestRunNestedAsyncAwaitWorksInInterp(t *testing.T) {
	// cbackend паникует на этом сценарии (планировщик корутин ещё не
	// поддерживает вложенность, internal/backend/cbackend/coroutine.go,
	// rech_coro_await_run) - интерпретатору вложенность не стоит ничего
	// (обычная Go-горутина внутри другой), см. package doc concurrency.go
	// про это осознанное, узкое расхождение backend'ов.
	out := runSrc(t, `
асинхронная функция б(): Целое
{
    вернуть 2
}
асинхронная функция а(): Целое
{
    вернуть дождаться б()
}
функция главная
{
    переменная результат = дождаться а()
    вывести `+"`${"+`результат}\n`+"`"+`
}
`)
	if out != "2\n" {
		t.Fatalf("ожидалось \"2\", получено %q", out)
	}
}

