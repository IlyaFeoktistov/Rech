package interp

import "testing"

func TestRunSerializeExprEntityListPrimitivesRoundTrip(t *testing.T) {
	got := runSrc(t, `
сущность Адрес
{
    имеет:
        город: Строка
}
сущность Пользователь
{
    имеет:
        имя: Строка
        возраст: Целое
        активен: Логическое
        адрес: Адрес
}
функция главная
{
    переменная а = новый Адрес()
    а.город = "Москва"
    переменная п = новый Пользователь()
    п.имя = `+"`"+`Аня "А"`+"`"+`
    п.возраст = 30
    п.активен = истина
    п.адрес = а
    вывести `+"`${"+`сериализовать JSON п}\n`+"`"+`

    переменная числа = новый Список<Целое>()
    числа.добавить(1)
    числа.добавить(2)
    числа.добавить(3)
    вывести `+"`${"+`сериализовать JSON числа}\n`+"`"+`

    вывести `+"`${"+`сериализовать JSON 42}\n`+"`"+`
    вывести `+"`${"+`сериализовать JSON "текст"}\n`+"`"+`
    вывести `+"`${"+`сериализовать JSON ложь}\n`+"`"+`

    переменная восстановленный = разобрать JSON (сериализовать JSON п) как Пользователь
    вывести `+"`${"+`восстановленный.имя}\n`+"`"+`
    вывести `+"`${"+`восстановленный.адрес.город}\n`+"`"+`
}
`)
	want := "{\"имя\":\"Аня \\\"А\\\"\",\"возраст\":30,\"активен\":true,\"адрес\":{\"город\":\"Москва\"}}\n" +
		"[1,2,3]\n42\n\"текст\"\nfalse\nАня \"А\"\nМосква\n"
	if got != want {
		t.Fatalf("получили %q, хотели %q", got, want)
	}
}
