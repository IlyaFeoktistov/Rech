package interp

import "testing"

// TestOverloadedFunctionsResolveDistinctBodies - обе перегрузки (по типу и по
// количеству параметров) реально исполняются как РАЗНЫЕ функции, не
// последняя зарегистрированная (см. internal/semantic/overload.go -
// перегрузка резолвится ЦЕЛИКОМ в semantic, interp просто исполняет функцию
// под уже готовым мангл-именем).
func TestOverloadedFunctionsResolveDistinctBodies(t *testing.T) {
	out := runSrc(t, `
функция сложить(а: Целое, б: Целое): Целое
{
    вернуть а + б
}
функция сложить(а: Строка, б: Строка): Строка
{
    вернуть а + б
}
функция сложить(а: Целое, б: Целое, ц: Целое): Целое
{
    вернуть а + б + ц
}
функция главная
{
    вывести `+"`${"+`сложить(2, 3)}\n`+"`"+`
    вывести `+"`${"+`сложить("привет, ", "мир")}\n`+"`"+`
    вывести `+"`${"+`сложить(1, 2, 3)}\n`+"`"+`
}
`)
	want := "5\nпривет, мир\n6\n"
	if out != want {
		t.Fatalf("ожидался вывод %q, получено %q", want, out)
	}
}
