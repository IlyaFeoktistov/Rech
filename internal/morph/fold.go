package morph

import "strings"

// foldYo сворачивает "ё"/"Ё" в "е"/"Е". Причина: "ё" в русской раскладке
// часто не набирают (клавиша "ё" физически отдельная и её пропускают), а
// словоформы, которые её действительно требуют ("вошёл", "войдёт"), от
// этого визуально не отличаются от написанных без "ё" ("вошел", "войдет").
// Разница - не опечатка, а обычный способ набора, поэтому обратный поиск
// (Dictionary.Analyze) должен находить лемму независимо от того, какой
// вариант написан - см. docs/MORPHOLOGY.md, раздел "ё/е".
//
// Коллизия из-за свёртки (два разных слова, отличающихся только "ё"/"е",
// например "все"/"всё") не тихая ошибка - она проявится как обычная
// неоднозначность в Dictionary.Analyze (несколько Analysis для одной
// словоформы), которую вызывающий код и так обязан разрешать - как любой
// другой синкретизм.
func foldYo(s string) string {
	if !strings.ContainsAny(s, "ёЁ") {
		return s
	}
	return strings.NewReplacer("ё", "е", "Ё", "Е").Replace(s)
}
