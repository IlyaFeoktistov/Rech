// initKind - тип нового проекта "rech init --<флаг>": значение
// "сборка.тип", главный файл, строки секции "сборка:" и его содержимое.
// libPrefix - имя проекта получает "lib" впереди: "-l<имя>" у линковщика
// ищет файл "lib<имя>.*".
type initKind struct {
	buildLines string
	mainFile   string
	source     string
	libPrefix  bool
}

